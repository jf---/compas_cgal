"""Run the exact gouge audit on the five published Held toolpaths; print and record the table.

Each path is generated live (:mod:`benchmarks.held_gouge_workloads`) and
audited against its case's analytic boundary (:mod:`benchmarks.held_gouge_audit`).
The audit's own clock is gated against ``AUDIT_BUDGET_S``; generation time is
reported beside it and not gated here.
"""

from __future__ import annotations

import argparse
import pathlib
from collections import Counter
from dataclasses import dataclass

from benchmarks.errors import BenchmarkError
from benchmarks.held_gouge_audit import REPORTING_SPLIT_MM
from benchmarks.held_gouge_audit import HeldGougeAuditReport
from benchmarks.held_gouge_workloads import WORKLOADS
from benchmarks.held_gouge_workloads import audit_generated
from benchmarks.held_gouge_workloads import generate
from benchmarks.performance_record import REPOSITORY
from benchmarks.performance_record import build_identity
from benchmarks.performance_record import machine_identity

OUTPUT = REPOSITORY / "benchmarks/results/held_gouge_audit.md"
# Audit-only wall clock per workload, seconds, on the Apple M1 Max: the check
# must be cheap enough to run after every generation. Monstera is the largest.
AUDIT_BUDGET_S = 2.0


class GougeAuditBudgetError(BenchmarkError):
    """An audit exceeded its wall-clock budget."""


@dataclass(frozen=True)
class GougeAuditRow:
    """One workload's audit with the generation that produced its path."""

    workload: str
    report: HeldGougeAuditReport
    generation_seconds: float


def run(workload: str) -> GougeAuditRow:
    """Generate one published path and audit it exactly."""
    path = generate(workload)
    return GougeAuditRow(workload, audit_generated(path), path.generation_seconds)


def _kinds(report: HeldGougeAuditReport) -> str:
    counts = Counter(item.primitive_kind for item in report.gouges)
    return ", ".join(f"{kind} {counts[kind]}" for kind in ("concave-arc", "line", "convex-arc") if counts[kind]) or "none"


HEADER = (
    "| workload | circles | gouging circles (exact / > split) | touching circles | max circle depth mm "
    "| connectors | gouging connectors (exact / > split) | touching connectors | max connector depth mm "
    "| gouges by primitive | audit s | generation s |"
)


def row_line(row: GougeAuditRow) -> str:
    r = row.report
    return (
        f"| {row.workload} | {r.circles} | {len(r.gouging_circles)} / {r.above_split('circle')} | {len(r.touching_circles)} | {r.max_depth_mm('circle'):.6f} "
        f"| {r.connectors} | {len(r.gouging_connectors)} / {r.above_split('connector')} | {len(r.touching_connectors)} | {r.max_depth_mm('connector'):.6f} "
        f"| {_kinds(r)} | {r.seconds:.2f} | {row.generation_seconds:.1f} |"
    )


def markdown(rows: list[GougeAuditRow]) -> str:
    """The generated results page."""
    build, machine = build_identity(), machine_identity()
    lines = [
        "<!-- Generated by `pixi run held-gouge-audit` (benchmarks/held_gouge_audit_table.py); do not edit. -->",
        "",
        "# Held toolpath gouge audit",
        "",
        f"Commit `{build.commit[:10]}`{' (dirty)' if build.dirty else ''} · {machine.cpu_brand} · recorded {build.recorded_at}.",
        "",
        "A gouge is a path element whose swept tool disk leaves the analytic pocket: `dist(element, ∂P) < r`, decided exactly.",
        f"A touch is `dist == r` exactly (allowed). Depths are `r - dist`, reported as doubles; the split column counts gouges deeper than {REPORTING_SPLIT_MM:g} mm "
        "(reporting only, to compare with the 2026-10-17 Decimal audit).",
        f"Audit budget: {AUDIT_BUDGET_S:g} s per workload (audit clock only).",
        "",
        HEADER,
        "|" + "---|" * HEADER.count(" | ") + "---|",
        *map(row_line, rows),
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workloads", nargs="+", default=list(WORKLOADS), choices=list(WORKLOADS))
    parser.add_argument("--output", type=pathlib.Path, default=OUTPUT)
    args = parser.parse_args()
    rows = []
    for workload in args.workloads:
        row = run(workload)
        print(row_line(row), flush=True)
        rows.append(row)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(markdown(rows), encoding="utf-8")
    print(f"RECORD {args.output}")
    over = [row for row in rows if row.report.seconds > AUDIT_BUDGET_S]
    if over:
        raise GougeAuditBudgetError("; ".join(f"{row.workload}: audit {row.report.seconds:.2f} s > {AUDIT_BUDGET_S} s" for row in over))


if __name__ == "__main__":
    main()
