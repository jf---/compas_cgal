"""Every results record the docs include is loadable and is the exact render of its JSON.

The docs pull generated Markdown in with ``--8<-- "benchmarks/results/<name>.md"``.
That include bypasses the generator, so a record rendered from a stale schema,
by an older renderer, or edited by hand would reach the site unnoticed. This
guard discovers every such include, resolves the generator from the record's
first line (``<!-- Generated by tools/<module>.py ...``), and asserts:

1. the generator's loader accepts the recorded JSON (the schema check), and
2. rendering that loaded record reproduces the included ``.md`` byte for byte.

A generator is checked through, in order: the rendered-record protocol
(``SCHEMA``, ``JSON_PATH``, ``MD_PATH``, ``load_record``, ``render_markdown``);
a named codec built from its real public load/render pair; or the unversioned
JSON shape (``JSON_PATH``, ``MARKDOWN_PATH``, bare ``json.loads``, ``render``).
A generator with no load/render path at all is listed in
``LEGACY_UNVERSIONED`` with the exact records it owns; a record whose header
names a legacy generator that does not own it is still checked (and fails).
Any other generator fails.
"""

from __future__ import annotations

import importlib
import json
import re
from dataclasses import dataclass
from pathlib import Path
from types import ModuleType
from typing import Callable
from typing import Mapping
from typing import Optional

import pytest

from tools.gate_vectors import GATE_TABLE_PATH
from tools.gate_vectors import GATE_VECTORS_PATH
from tools.gate_vectors import load_gate_vectors
from tools.pipeline_timing_results import PIPELINE_TIMING_PATH
from tools.pipeline_timing_results import PIPELINE_TIMING_TABLE_PATH
from tools.pipeline_timing_results import load_pipeline_timings

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs"
RESULTS_PREFIX = "benchmarks/results/"

INCLUDE = re.compile(r"""--8<--\s+["']([^"']+)["']""")
GENERATED_BY = "<!-- Generated by"
# The first `tools/<module>.py`, `tools.<module>` or `benchmarks/<module>.py` on the header line.
GENERATOR = re.compile(r"\b(tools|benchmarks)[/.]([A-Za-z_][A-Za-z0-9_]*)")

PROTOCOL = ("SCHEMA", "JSON_PATH", "MD_PATH", "load_record", "render_markdown")
UNVERSIONED_SHAPE = ("JSON_PATH", "MARKDOWN_PATH", "render")


@dataclass(frozen=True)
class LegacyGenerator:
    """A generator exempt from the load/render checks, and the only records it may exempt."""

    records: tuple[str, ...]
    reason: str


# Generators with no load-from-JSON / render pair. This set may only shrink
# (`test_the_exemption_lists_only_shrink` pins its size): give a generator
# `load_record` + `render_markdown` (or a loader beside its renderer) and remove
# it here; `test_legacy_generators_still_lack_a_codec` fails until it is removed,
# and `test_every_listed_record_is_included_and_names_its_generator` fails on an
# entry no included record matches any more.
LEGACY_UNVERSIONED: Mapping[str, LegacyGenerator] = {
    "tools.held_connector_engagement_survey": LegacyGenerator(("benchmarks/results/held_connector_engagement.md",), "renders in-memory survey rows; no JSON loader"),
    "tools.held_connector_engagement_tier2": LegacyGenerator(("benchmarks/results/held_connector_engagement_tier2.md",), "renders in-memory tier-2 rows; no JSON loader"),
    "benchmarks.held_gouge_audit_table": LegacyGenerator(("benchmarks/results/held_gouge_audit.md",), "renders live audit rows; records no JSON"),
    "tools.performance_callpaths": LegacyGenerator(("benchmarks/results/performance_fig5_callpaths.md",), "renders build/performance/held_figure5.prof, an uncommitted profile"),
    "tools.pipeline_time_gate": LegacyGenerator(
        ("benchmarks/results/pipeline_time_gate.md",),
        "composes a git-committed base, two JSON records and pinned base constants (held by tests/tools/test_pipeline_time_gate.py)",
    ),
}

# Unversioned records: the loader is bare `json.loads`, so there is no schema
# to check; the byte-exact render is still asserted. Each maps to the record it
# owns, which must equal the tool's own MARKDOWN_PATH. May only shrink
# (`test_the_exemption_lists_only_shrink` pins its size).
UNVERSIONED_JSON: Mapping[str, str] = {
    "tools.held_connector_repair_budget_results": "benchmarks/results/held_connector_repair_budget.md",
    "tools.held_splice_ab_results": "benchmarks/results/held_splice_ab.md",
    "tools.held_native_clearance_results": "benchmarks/results/held_native_clearance.md",
    "tools.held_omega_coverage_results": "benchmarks/results/held_omega_coverage.md",
    "tools.held_omega_connector_gate_results": "benchmarks/results/held_omega_connector_gate.md",
    "tools.held_omega_connector_repair_results": "benchmarks/results/held_omega_connector_repair.md",
}

# Ratchet: the sizes of the two exemption lists today. Growing a list fails;
# shrinking one fails until its ceiling is lowered to match, so a removed
# exemption cannot silently be re-added later.
LEGACY_UNVERSIONED_CEILING = 5
UNVERSIONED_JSON_CEILING = 6


class IncludedRecordError(Exception):
    """An included record cannot be attributed to a generator."""


class MissingIncludedRecordError(IncludedRecordError):
    """A docs page includes a record file that does not exist."""


class MissingGeneratorHeaderError(IncludedRecordError):
    """An included record does not name its generator on its first line."""


class UnclassifiedGeneratorError(Exception):
    """A generator follows no known load/render pattern and is not listed as legacy."""


class ForeignRecordError(Exception):
    """A record's header names a listed generator that does not own that record."""


@dataclass(frozen=True)
class RecordCodec:
    """How one generator loads its JSON record and renders the included Markdown."""

    json_path: Path
    md_path: Path
    load: Callable[[], object]
    render: Callable[[object], str]


def _actual_stock_profile(module: ModuleType) -> RecordCodec:
    return RecordCodec(
        module.JSON_PATH,
        module.MD_PATH,
        lambda: module.ProfileRecord.from_json(module.JSON_PATH.read_text(encoding="utf-8")),
        module.render_markdown,
    )


def _gate_table(module: ModuleType) -> RecordCodec:
    return RecordCodec(ROOT / GATE_VECTORS_PATH, ROOT / GATE_TABLE_PATH, lambda: load_gate_vectors(ROOT / GATE_VECTORS_PATH), module.render_gate_table)


def _pipeline_timing_table(module: ModuleType) -> RecordCodec:
    return RecordCodec(
        ROOT / PIPELINE_TIMING_PATH,
        ROOT / PIPELINE_TIMING_TABLE_PATH,
        lambda: load_pipeline_timings(ROOT / PIPELINE_TIMING_PATH),
        module.render_pipeline_timing_table,
    )


# Generators whose real public API is a versioned load/render pair under other names.
NAMED_CODECS: Mapping[str, Callable[[ModuleType], RecordCodec]] = {
    "tools.actual_stock_profile": _actual_stock_profile,
    "tools.gate_table": _gate_table,
    "tools.pipeline_timing_table": _pipeline_timing_table,
}


def _results_includes() -> dict[str, tuple[str, ...]]:
    """Map each include target under ``benchmarks/results/`` to the docs pages that include it."""
    pages: dict[str, list[str]] = {}
    for page in sorted(DOCS.rglob("*.md")):
        for target in INCLUDE.findall(page.read_text(encoding="utf-8")):
            if target.startswith(RESULTS_PREFIX):
                pages.setdefault(target, []).append(page.relative_to(ROOT).as_posix())
    return {target: tuple(names) for target, names in sorted(pages.items())}


def generator_of(record: Path) -> str:
    """The dotted module named on the record's ``Generated by`` header.

    Raises:
        MissingIncludedRecordError: the record file does not exist.
        MissingGeneratorHeaderError: the first line is not a generator header.
    """
    if not record.is_file():
        raise MissingIncludedRecordError(f"{record.relative_to(ROOT)} is included by {RESULTS_INCLUDES.get(record.relative_to(ROOT).as_posix())} but does not exist")
    first = record.read_text(encoding="utf-8").split("\n", 1)[0]
    match = GENERATOR.search(first)
    if not first.startswith(GENERATED_BY) or match is None:
        raise MissingGeneratorHeaderError(f"{record.relative_to(ROOT)}: first line {first[:80]!r} names no generator")
    return f"{match.group(1)}.{match.group(2)}"


def _has(module: ModuleType, names: tuple[str, ...]) -> bool:
    return all(hasattr(module, name) for name in names)


def _unversioned(module: ModuleType) -> RecordCodec:
    return RecordCodec(module.JSON_PATH, module.MARKDOWN_PATH, lambda: json.loads(module.JSON_PATH.read_text(encoding="utf-8")), module.render)


def codec_for(name: str) -> RecordCodec:
    """Resolve a generator to its codec.

    Raises:
        UnclassifiedGeneratorError: no protocol, named codec or unversioned listing applies.
    """
    module = importlib.import_module(name)
    if _has(module, PROTOCOL):
        return RecordCodec(module.JSON_PATH, module.MD_PATH, lambda: module.load_record(module.JSON_PATH), module.render_markdown)
    if name in NAMED_CODECS:
        return NAMED_CODECS[name](module)
    if name in UNVERSIONED_JSON:
        return _unversioned(module)
    if name in LEGACY_UNVERSIONED:
        raise ForeignRecordError(f"{name} is legacy-exempt only for {LEGACY_UNVERSIONED[name].records}")
    raise UnclassifiedGeneratorError(f"{name} has no rendered-record protocol ({', '.join(PROTOCOL)}), no named codec, and is not in LEGACY_UNVERSIONED")


def _generator_or_none(record: str) -> Optional[str]:
    try:
        return generator_of(ROOT / record)
    except IncludedRecordError:
        return None


def _exempt(record: str) -> bool:
    generator = _generator_or_none(record)
    return generator in LEGACY_UNVERSIONED and record in LEGACY_UNVERSIONED[generator].records


RESULTS_INCLUDES = _results_includes()
INCLUDED = {target: pages for target, pages in RESULTS_INCLUDES.items() if target.endswith(".md")}
# A missing or header-less record fails `test_record_names_its_generator` alone.
CHECKED = [record for record in INCLUDED if _generator_or_none(record) is not None and not _exempt(record)]


def _codec(record: str) -> RecordCodec:
    codec = codec_for(generator_of(ROOT / record))
    assert codec.md_path.resolve() == (ROOT / record).resolve(), f"{record}: the generator renders {codec.md_path}, not the included file"
    return codec


def test_the_docs_include_records() -> None:
    assert INCLUDED, f'no `--8<-- "{RESULTS_PREFIX}*.md"` include under {DOCS}'


def test_every_results_include_is_a_whole_markdown_record() -> None:
    """A results include that is not a plain ``.md`` (a line range, another file type) would escape the guard."""
    others = {target: pages for target, pages in RESULTS_INCLUDES.items() if target not in INCLUDED}
    assert not others, f"results includes the guard cannot check: {others}"


@pytest.mark.parametrize("record", list(INCLUDED), ids=[Path(r).stem for r in INCLUDED])
def test_record_names_its_generator(record: str) -> None:
    generator_of(ROOT / record)


@pytest.mark.parametrize("record", CHECKED, ids=[Path(r).stem for r in CHECKED])
def test_record_loads(record: str) -> None:
    _codec(record).load()


@pytest.mark.parametrize("record", CHECKED, ids=[Path(r).stem for r in CHECKED])
def test_record_is_the_render_of_its_json(record: str) -> None:
    codec = _codec(record)
    assert codec.render(codec.load()).encode("utf-8") == (ROOT / record).read_bytes(), f"{record} is not the render of {codec.json_path.relative_to(ROOT)}"


def _listed_records() -> list[tuple[str, str]]:
    owned = [(name, record) for name, legacy in LEGACY_UNVERSIONED.items() for record in legacy.records]
    return owned + list(UNVERSIONED_JSON.items())


@pytest.mark.parametrize(("name", "record"), _listed_records(), ids=[Path(r).stem for _, r in _listed_records()])
def test_every_listed_record_is_included_and_names_its_generator(name: str, record: str) -> None:
    assert record in INCLUDED, f"{name} lists {record}, which no docs page includes"
    assert generator_of(ROOT / record) == name, f"{record} does not name {name} as its generator"


def test_every_named_codec_is_still_included() -> None:
    included = {_generator_or_none(record) for record in INCLUDED}
    assert set(NAMED_CODECS) <= included, f"named codecs no included record names: {sorted(set(NAMED_CODECS) - included)}"


def test_the_exemption_lists_only_shrink() -> None:
    assert len(LEGACY_UNVERSIONED) == LEGACY_UNVERSIONED_CEILING, "LEGACY_UNVERSIONED may only shrink; lower its ceiling when it does"
    assert len(UNVERSIONED_JSON) == UNVERSIONED_JSON_CEILING, "UNVERSIONED_JSON may only shrink; lower its ceiling when it does"


def test_the_listings_are_disjoint() -> None:
    assert not set(LEGACY_UNVERSIONED) & set(NAMED_CODECS)
    assert not set(LEGACY_UNVERSIONED) & set(UNVERSIONED_JSON)
    assert not set(NAMED_CODECS) & set(UNVERSIONED_JSON)


@pytest.mark.parametrize("name", sorted(LEGACY_UNVERSIONED))
def test_legacy_generators_still_lack_a_codec(name: str) -> None:
    module = importlib.import_module(name)
    assert not _has(module, PROTOCOL), f"{name} now meets the rendered-record protocol; remove it from LEGACY_UNVERSIONED"
    assert not _has(module, UNVERSIONED_SHAPE), f"{name} now has JSON_PATH/MARKDOWN_PATH/render; move it to UNVERSIONED_JSON"


@pytest.mark.parametrize("name", sorted(UNVERSIONED_JSON))
def test_unversioned_generators_still_lack_the_protocol(name: str) -> None:
    module = importlib.import_module(name)
    assert _has(module, UNVERSIONED_SHAPE), f"{name} lost JSON_PATH/MARKDOWN_PATH/render"
    assert module.MARKDOWN_PATH.resolve() == (ROOT / UNVERSIONED_JSON[name]).resolve(), f"{name} renders {module.MARKDOWN_PATH}, not {UNVERSIONED_JSON[name]}"
    assert not _has(module, PROTOCOL), f"{name} now meets the rendered-record protocol; remove it from UNVERSIONED_JSON"
