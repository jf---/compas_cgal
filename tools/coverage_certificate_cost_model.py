"""Design-time cost-model inputs of the coverage certificate on the generated Monstera path.

Reporting only. Counts the regions the certificate's design would see (one
region per full-circle cut, one capsule per non-degenerate straight connector
piece) and how many bounding boxes overlap each region's box: the ``k`` of the
O(N k log k) cost model on ``docs/held_coverage_certificate.md``. Boxes are
binary64 roundings; the counts describe the workload, they decide nothing.

The certificate as built merges connector capsules per domain edge
(``connector regions`` in ``coverage_certificate_acceptance.md``); this tool
deliberately counts the unmerged design-time pieces.

Run: ``pixi run coverage-certificate-cost-model``; it rewrites
``benchmarks/results/coverage_certificate_cost_model.{json,md}``.
"""

from __future__ import annotations

import argparse
import dataclasses
import json
import pathlib
from collections.abc import Sequence
from dataclasses import dataclass

import numpy as np

from benchmarks.performance_record import REPOSITORY
from benchmarks.performance_record import BuildIdentity
from benchmarks.performance_record import MachineIdentity
from benchmarks.performance_record import build_identity
from benchmarks.performance_record import machine_identity
from tools.coverage_certificate_monstera_path import FloatArray
from tools.coverage_certificate_monstera_path import MonsteraPathArrays
from tools.coverage_certificate_monstera_path import load_monstera_path

SCHEMA = "coverage-certificate-cost-model/1"
JSON_PATH = REPOSITORY / "benchmarks/results/coverage_certificate_cost_model.json"
MD_PATH = REPOSITORY / "benchmarks/results/coverage_certificate_cost_model.md"
GENERATED_BY = "Generated by tools/coverage_certificate_cost_model.py; do not edit, run `pixi run coverage-certificate-cost-model`."
NEIGHBOUR_PERCENTILE = 90


@dataclass(frozen=True)
class CostModelInputs:
    """Region and neighbour counts of one path.

    ``boundary_pieces`` is 2 per annulus, 1 per disk, 4 per capsule
    (two caps, two flanks) and 5 per centre-domain vertex (the polygon edge and
    its capsule's two caps and two flanks).
    """

    workload: str
    generation_s: float
    cuts: int
    annuli: int
    disks: int
    connectors: int
    connector_samples: int
    connector_pieces: int
    domain_vertices: int
    regions: int
    neighbours_median: float
    neighbours_p90: float
    neighbours_max: int
    overlapping_pairs: int
    boundary_pieces: int


@dataclass(frozen=True)
class CostModelRecord:
    generated_by: str
    schema: str
    identity: MachineIdentity
    build: BuildIdentity
    inputs: CostModelInputs

    def to_json(self) -> str:
        return json.dumps(dataclasses.asdict(self), indent=2) + "\n"


def _connector_pieces(samples: Sequence[FloatArray]) -> FloatArray:
    """(p, 2, 2) straight connector pieces with distinct endpoints."""
    pieces = [(a, b) for polyline in samples for a, b in zip(polyline, polyline[1:]) if np.any(a != b)]
    return np.array(pieces).reshape(-1, 2, 2)


def _box_neighbours(lo: FloatArray, hi: FloatArray) -> np.ndarray:
    """For each closed box, the number of other boxes it overlaps."""
    counts = np.empty(len(lo), dtype=np.int64)
    for i in range(len(lo)):
        overlap = np.all(lo <= hi[i], axis=1) & np.all(hi >= lo[i], axis=1)
        counts[i] = int(overlap.sum()) - 1
    return counts


def cost_model_inputs(path: MonsteraPathArrays) -> CostModelInputs:
    """Count the design-time regions of ``path`` and their bounding-box neighbours."""
    r = path.tool_radius
    reach = path.radii + r
    pieces = _connector_pieces(path.connector_samples)
    lo = np.vstack([path.centres - reach[:, None], pieces.min(axis=1) - r])
    hi = np.vstack([path.centres + reach[:, None], pieces.max(axis=1) + r])
    neighbours = _box_neighbours(lo, hi)
    annuli = int((path.radii > r).sum())
    disks = len(path.radii) - annuli
    vertices = len(path.centre_domain)
    return CostModelInputs(
        workload=path.workload,
        generation_s=path.generation_s,
        cuts=len(path.radii),
        annuli=annuli,
        disks=disks,
        connectors=len(path.connector_samples),
        connector_samples=sum(len(s) for s in path.connector_samples),
        connector_pieces=len(pieces),
        domain_vertices=vertices,
        regions=len(lo),
        neighbours_median=float(np.median(neighbours)),
        neighbours_p90=float(np.percentile(neighbours, NEIGHBOUR_PERCENTILE)),
        neighbours_max=int(neighbours.max()),
        overlapping_pairs=int(neighbours.sum()) // 2,
        boundary_pieces=2 * annuli + disks + 4 * len(pieces) + 5 * vertices,
    )


def render_markdown(record: CostModelRecord) -> str:
    """The docs table of one cost-model record."""
    m, build = record.inputs, record.build
    lines = [
        f"<!-- {record.generated_by} -->",
        "",
        f"Design-time cost-model inputs on the generated `{m.workload}` path (closing seam connector included), "
        f"commit `{build.commit[:12]}`{' (dirty tree)' if build.dirty else ''}, {build.recorded_at}. "
        "Bounding boxes are binary64 roundings; reporting only. Connector pieces are the unmerged straight pieces of the connector polylines.",
        "",
        "| quantity | value |",
        "|---|---|",
        f"| full-circle cuts | {m.cuts} ({m.annuli} annuli, {m.disks} disks) |",
        f"| connector straight pieces | {m.connector_pieces} (from {m.connector_samples} samples on {m.connectors} connectors) |",
        f"| Ω vertices | {m.domain_vertices} |",
        f"| regions (cuts + connector pieces) | {m.regions} |",
        f"| bbox neighbours per region | median {m.neighbours_median:g}, p{NEIGHBOUR_PERCENTILE} {m.neighbours_p90:g}, max {m.neighbours_max} |",
        f"| overlapping region pairs | {m.overlapping_pairs:,} |",
        f"| boundary pieces (2·annuli + disks + 4·pieces + 5·vertices) | {m.boundary_pieces:,} |",
        f"| path generation (stage clocks, this run) | {m.generation_s:.1f} s |",
    ]
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--json", type=pathlib.Path, default=JSON_PATH)
    parser.add_argument("--md", type=pathlib.Path, default=MD_PATH)
    args = parser.parse_args(argv)
    record = CostModelRecord(GENERATED_BY, SCHEMA, machine_identity(), build_identity(), cost_model_inputs(load_monstera_path()))
    args.json.write_text(record.to_json(), encoding="utf-8")
    args.md.write_text(render_markdown(record), encoding="utf-8")


if __name__ == "__main__":
    main()
