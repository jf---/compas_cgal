"""Render the pinned gate vectors as the Markdown table the docs include.

The docs never type a gate number: `docs/machining_quality.md` includes
`benchmarks/results/gate_vectors.md` through `pymdownx.snippets`, and that file
is this module's rendering of `benchmarks/results/gate_vectors.json`.
`tests/tools/test_gate_table.py` holds the committed table to the committed
vectors byte for byte.
"""

from __future__ import annotations

from benchmarks.gate import GATE_CAP_CASES
from tools.gate_vectors import CASE_KEY_SEPARATOR
from tools.gate_vectors import REQUIRED_CAP
from tools.gate_vectors import REQUIRED_COMPONENTS
from tools.gate_vectors import CriterionSpec
from tools.gate_vectors import GateVectors


class UnknownGateCapError(Exception):
    """A case names a cap id the gate does not define."""


def _required(criterion: CriterionSpec, cap_deg: float) -> str:
    if criterion.direction == "reported":
        return "reported"
    if criterion.direction == "wallclock":
        return "time"
    if criterion.required == REQUIRED_CAP:
        return f"<= {cap_deg:g}"
    if criterion.required == REQUIRED_COMPONENTS:
        return "<= components"
    return f"<= {criterion.required}"


def _short(generator: str) -> str:
    return generator.replace("engagement_controlled", "eng-ctrl").replace("radius_regulated", "radius-reg")


def render_gate_table(vectors: GateVectors) -> str:
    """The Markdown tables of *vectors*, one per cap, gated rows marked.

    Args:
        vectors: The validated vectors.

    Returns:
        The Markdown text, ending in a newline.

    Raises:
        UnknownGateCapError: A case's cap id is not one of the gate's caps.
    """
    caps = dict(GATE_CAP_CASES)
    instrument = ", ".join(f"{key} {value}" for key, value in vectors.instrument.items())
    lines = [
        f"<!-- Generated by tools.gate_table from benchmarks/results/gate_vectors.json (rules {vectors.rules_version}). Do not edit; run `pixi run gate-vectors`. -->",
        "",
        f"Gate rules {vectors.rules_version}; instrument: {instrument}. Gated rows are **bold**; wall-clock rows are this machine's and are never compared.",
    ]
    cap_ids = list(dict.fromkeys(key.split(CASE_KEY_SEPARATOR)[0] for key in vectors.cases))
    for cap_id in cap_ids:
        if cap_id not in caps:
            raise UnknownGateCapError(f"case cap id {cap_id!r} is not a gate cap ({sorted(caps)}).")
        cap_deg = float(caps[cap_id])
        keys = [key for key in vectors.cases if key.split(CASE_KEY_SEPARATOR)[0] == cap_id]
        headers = ["<br>".join((pocket, _short(generator))) for _cap, generator, pocket in (key.split(CASE_KEY_SEPARATOR) for key in keys)]
        lines += [
            "",
            f"**{cap_id}** (cap {cap_deg:g} deg)",
            "",
            "| group | metric | required | " + " | ".join(headers) + " |",
            "| :--- | :--- | :--- | " + " | ".join("---:" for _ in keys) + " |",
        ]
        for criterion in vectors.criteria:
            name = f"**`{criterion.name}`**" if criterion.direction == "lower" else f"`{criterion.name}`"
            values = " | ".join(vectors.cases[key][criterion.name] for key in keys)
            lines.append(f"| {criterion.group} | {name} | {_required(criterion, cap_deg)} | {values} |")
    return "\n".join(lines) + "\n"
