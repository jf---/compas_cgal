"""The Figure 5 call-path table of docs/performance.md, rendered from the Figure 5 profile.

`docs/performance.md` includes `benchmarks/results/performance_fig5_callpaths.md`
through `pymdownx.snippets`; this module writes it from
``build/performance/held_figure5.prof``. Every row names its functions, and a
renamed function fails the run (`tools.performance_stats`). Run as
``pixi run performance-figures``.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass

from tools.performance_stats import ProfileStats
from tools.performance_stats import call_count
from tools.performance_stats import cumulative_s
from tools.performance_stats import load_stats
from tools.performance_workloads import HELD_FIGURE5
from tools.performance_workloads import ROOT
from tools.performance_workloads import read_profile_meta

CALLPATHS_PATH = ROOT / "benchmarks" / "results" / "performance_fig5_callpaths.md"
# Rendered precision of profiled seconds: tenths.
SECONDS_DECIMALS = 1
MILLION = 1_000_000
# `fractions.Fraction` routes every binary operator through `forward`; each call is one operation.
FRACTION_MODULE = "fractions.py"
FRACTION_OPERATOR = "forward"
GCD = "<built-in method math.gcd>"
GCD_MODULE = "~"
# The wired clearance: the native batch query and its per-site exact decode.
CLEARANCE_MODULE = "held_boundary_clearance.py"
CLEARANCE_QUERY = "distance_admissible_sites"
CLEARANCE_DECODE = "_site"


@dataclass(frozen=True)
class CallPathRow:
    """One rendered row.

    Attributes:
        path: The call-path cell (Markdown).
        cumulative: The cumulative-seconds cell.
        calls: The calls cell.
    """

    path: str
    cumulative: str
    calls: str


def _s(value: float) -> str:
    return f"{value:.{SECONDS_DECIMALS}f} s"


def _calls(value: int) -> str:
    return f"{value:,}"


def _millions(value: int) -> str:
    return f"{value / MILLION:.1f} M"


def callpath_rows(stats: ProfileStats) -> list[CallPathRow]:
    """The table rows of the Figure 5 profile.

    Args:
        stats: The Figure 5 profile.

    Returns:
        The rows, in table order.

    Raises:
        MissingProfileFunctionError: A function a row reads is not in the profile.
    """

    def row(label: str, name: str) -> CallPathRow:
        return CallPathRow(label, _s(cumulative_s(stats, name)), _calls(call_count(stats, name)))

    lookup, batch = "_native_station_boundary", "_native_station_boundary_analyses"
    return [
        row("`build_figure5_approximate_path` (initial placement)", "build_figure5_approximate_path"),
        row("→ `build_distance_admissible_hypotheses`", "build_distance_admissible_hypotheses"),
        row(f"→ `{lookup}` (station lookup; the first builds the batch)", lookup),
        row(f"→ `{batch}` (one native AABB batch per guide)", batch),
        CallPathRow(
            f"→ `{CLEARANCE_QUERY}` (native kernel) → `{CLEARANCE_DECODE}` (hex → integers; exact `Fraction`s on demand)",
            f"{_s(cumulative_s(stats, CLEARANCE_QUERY, CLEARANCE_MODULE))} / {_s(cumulative_s(stats, CLEARANCE_DECODE, CLEARANCE_MODULE))}",
            f"{_calls(call_count(stats, CLEARANCE_QUERY, CLEARANCE_MODULE))} / {_calls(call_count(stats, CLEARANCE_DECODE, CLEARANCE_MODULE))}",
        ),
        CallPathRow(
            "`fractions.Fraction` arithmetic, whole profile",
            _s(cumulative_s(stats, FRACTION_OPERATOR, FRACTION_MODULE)),
            f"{_millions(call_count(stats, FRACTION_OPERATOR, FRACTION_MODULE))} operations, {_millions(call_count(stats, GCD, GCD_MODULE))} `gcd`",
        ),
        row("`load_held_reference_case` (biarc reconstruction or its content-addressed cache read, outside the timed stage)", "load_held_reference_case"),
    ]


def render_callpaths(stats: ProfileStats, commit: str, dirty: bool, profiled_on: str) -> str:
    """The Markdown the docs include.

    Args:
        stats: The Figure 5 profile.
        commit: The commit the profile was taken at.
        dirty: Whether the working tree had uncommitted changes.
        profiled_on: The profile date.

    Returns:
        The Markdown text, ending in a newline.
    """
    tree = " (working tree with uncommitted changes)" if dirty else ""
    lines = [
        "<!-- Generated by tools.performance_callpaths from build/performance/held_figure5.prof. Do not edit; run `pixi run performance-figures`. -->",
        "",
        (
            f"cProfile of `benchmarks.held_toolpath_benchmark.{HELD_FIGURE5.target}`, one cold run in a fresh process, "
            f"{profiled_on}, commit `{commit[:12]}`{tree}; total profiled time {_s(stats.total_tt)}."
        ),
        "",
        "| call path | cumulative (profiled) | calls |",
        "| --- | ---: | ---: |",
    ]
    lines += [f"| {row.path} | {row.cumulative} | {row.calls} |" for row in callpath_rows(stats)]
    return "\n".join(lines) + "\n"


def main() -> int:
    """Write the Figure 5 call-path table.

    Returns:
        The process exit status.
    """
    meta = read_profile_meta(HELD_FIGURE5)
    text = render_callpaths(load_stats(HELD_FIGURE5.profile_path), str(meta["commit"]), bool(meta["dirty"]), str(meta["date"]))
    CALLPATHS_PATH.write_text(text)
    print(f"wrote {CALLPATHS_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
