"""Render the serial generation-time results as the Markdown the docs include.

The docs never type a timing: `docs/pipeline.md` includes
`benchmarks/results/pipeline_timing.md` through `pymdownx.snippets`, and that
file is this module's rendering of `benchmarks/results/pipeline_timing.json`.
`tests/tools/test_pipeline_timing.py` holds the committed rendering to the
committed document byte for byte.
"""

from __future__ import annotations

from tools.gate_case_keys import CASE_KEY_SEPARATOR
from tools.pipeline_timing_results import RUNS_PER_CASE
from tools.pipeline_timing_results import PipelineTimings

# Rendered precision of seconds: milliseconds.
RENDERED_SECONDS_DECIMALS = 3


def _seconds(value: float) -> str:
    return f"{value:.{RENDERED_SECONDS_DECIMALS}f}"


def render_pipeline_timing_table(timings: PipelineTimings) -> str:
    """The Markdown method statement and per-case table of *timings*.

    Args:
        timings: The validated timings.

    Returns:
        The Markdown text, ending in a newline.
    """
    lines = [
        "<!-- Generated by tools.pipeline_timing_table from benchmarks/results/pipeline_timing.json. Do not edit; run `pixi run pipeline-timing`. -->",
        "",
        (
            f"Serial generation time, measured by `tools.pipeline_timing`: every gate generator on every gate case, one case at a time "
            f"with nothing else running, each of {RUNS_PER_CASE} generations in a fresh process; the table reports the median. "
            "`generation_s` times the generator call alone: interpreter start-up, imports and pocket construction are outside it, "
            "first-call costs inside the generator are in it. Seconds are wall clock on the machine that ran the task and do not "
            "transfer to another machine; compare cases within one run of the task only. The operation count and the ops digest "
            "(SHA-256 over every operation's kind and geometry) are the same in all runs of a case, or the task fails."
        ),
        "",
        "| cap | generator | pocket | `generation_s` (median) | runs (s) | operations | ops digest |",
        "| :--- | :--- | :--- | ---: | ---: | ---: | :--- |",
    ]
    for key, case in timings.cases.items():
        cap_id, generator, pocket = key.split(CASE_KEY_SEPARATOR)
        runs = ", ".join(_seconds(run) for run in case.runs_s)
        lines.append(f"| {cap_id} | {generator} | {pocket} | {_seconds(case.median_s)} | {runs} | {case.operations} | `{case.digest}` |")
    if timings.excluded:
        lines += ["", "Excluded by the gate admissions, not generated: " + ", ".join(f"`{key}`" for key in timings.excluded) + "."]
    return "\n".join(lines) + "\n"
