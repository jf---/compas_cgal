"""Time and count the coverage certificate's circle-circle core on the frozen Monstera circles.

Input: the committed spike fixture ``tests/fixtures/coverage_certificate/monstera_circles.txt``
(4367 full-circle cuts, hex binary64) and ``monstera_centre_domain.txt``, the
same input ``test_monstera_circles_match_the_spike_counts`` pins. The counts are
deterministic; the times are wall clock under the recorded 1-minute load
average and do not transfer between machines or loads.

One extra run uses ``audit=True``: it re-witnesses every edge the counters call
covered by pure exact membership and raises on any disagreement, so a
completed audit run means every sub-arc agrees with the counters.

The split of the proven uncovered points by distance to the centre-domain
boundary is reporting only (binary64 roundings): connectors sweep exactly the
points within r of that boundary, so only points farther than r away are
beyond what the not-yet-modelled connectors could cut.

Run: ``pixi run coverage-certificate-circle-core``; it rewrites
``benchmarks/results/coverage_certificate_circle_core.{json,md}``.
"""

from __future__ import annotations

import argparse
import dataclasses
import json
import os
import pathlib
import statistics
import time
from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any

import numpy as np

from benchmarks.errors import BenchmarkError
from benchmarks.performance_record import REPOSITORY
from benchmarks.performance_record import BuildIdentity
from benchmarks.performance_record import MachineIdentity
from benchmarks.performance_record import build_identity
from benchmarks.performance_record import machine_identity
from compas_cgal.coverage_certificate.circle_core import CircleCoreReport
from compas_cgal.coverage_certificate.circle_core import FilterMode
from compas_cgal.coverage_certificate.circle_core import run_circle_core
from compas_cgal.coverage_certificate.sweeps import FullCircleSweep
from compas_cgal.coverage_certificate.target import CentreDomain
from compas_cgal.units import GuideRadius
from compas_cgal.units import Point2
from compas_cgal.units import ToolRadius
from compas_cgal.units import WorldXY

SCHEMA = "coverage-certificate-circle-core/1"
FIXTURES = REPOSITORY / "tests/fixtures/coverage_certificate"
JSON_PATH = REPOSITORY / "benchmarks/results/coverage_certificate_circle_core.json"
MD_PATH = REPOSITORY / "benchmarks/results/coverage_certificate_circle_core.md"
GENERATED_BY = "Generated by tools/coverage_certificate_circle_core.py; do not edit, run `pixi run coverage-certificate-circle-core`."
TIMING_RUNS = 3
# The native sum behind ``exact_fallbacks`` (coverage_certificate_2/counters_2.h).
FALLBACK_COUNTERS = (
    "pairs_exact",
    "materialised_pairs",
    "pair_towers",
    "exact_half",
    "exact_compare_x",
    "exact_membership",
    "exact_target_membership",
    "circle_line_exact",
    "line_line_exact",
    "materialised_line_events",
    "exact_tower_compares",
    "exact_line_side",
)


class CircleCoreRunsDisagreeError(BenchmarkError):
    """Two runs of the circle core on one input gave different decisions."""


class FallbackCountersError(BenchmarkError):
    """``exact_fallbacks`` is not the sum of ``FALLBACK_COUNTERS``: the native definition changed."""


class StaleCircleCoreRecordError(BenchmarkError):
    """The stored record has another schema; it must be re-measured, not rendered."""


@dataclass(frozen=True)
class TimedCoreRun:
    """One core run: wall seconds, native phase seconds and the 1-minute load average read just before it."""

    seconds: float
    phase_s: tuple[float, float, float, float]
    load_1min: float


@dataclass(frozen=True)
class CircleCoreRecord:
    generated_by: str
    schema: str
    identity: MachineIdentity
    build: BuildIdentity
    cuts: int
    domain_vertices: int
    counters: dict[str, int]
    exposed: int
    uncovered_in_target: int
    beyond_connector_reach: tuple[tuple[float, float], ...]
    runs: tuple[TimedCoreRun, ...]
    median_s: float
    audit: TimedCoreRun

    def to_json(self) -> str:
        return json.dumps(dataclasses.asdict(self), indent=2) + "\n"


def _core_run(raw: dict[str, Any]) -> TimedCoreRun:
    phases = raw["phase_s"]
    return TimedCoreRun(seconds=raw["seconds"], phase_s=(phases[0], phases[1], phases[2], phases[3]), load_1min=raw["load_1min"])


def load_record(path: pathlib.Path) -> CircleCoreRecord:
    """Read a record written by :meth:`CircleCoreRecord.to_json`.

    Raises:
        StaleCircleCoreRecordError: the record's schema is not ``SCHEMA``.
    """
    raw: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    if raw.get("schema") != SCHEMA:
        raise StaleCircleCoreRecordError(f"{path}: schema {raw.get('schema')!r}, expected {SCHEMA!r}; re-measure (`pixi run coverage-certificate-circle-core`), never render it")
    return CircleCoreRecord(
        **{
            **raw,
            "identity": MachineIdentity(**raw["identity"]),
            "build": BuildIdentity(**raw["build"]),
            "beyond_connector_reach": tuple((x, y) for x, y in raw["beyond_connector_reach"]),
            "runs": tuple(_core_run(run) for run in raw["runs"]),
            "audit": _core_run(raw["audit"]),
        }
    )


def _hex_lines(name: str) -> list[str]:
    return (FIXTURES / name).read_text(encoding="utf-8").split("\n")


def load_fixture() -> tuple[ToolRadius, list[FullCircleSweep], CentreDomain]:
    """The frozen Monstera cuts, tool radius and centre domain (hex binary64, exact)."""
    lines = _hex_lines("monstera_circles.txt")
    count, radius = lines[0].split()
    cuts = []
    for line in lines[1 : 1 + int(count)]:
        x, y, big_r = (float.fromhex(token) for token in line.split())
        cuts.append(FullCircleSweep.build(Point2[WorldXY].build(x, y), GuideRadius.build(big_r)))
    domain_lines = _hex_lines("monstera_centre_domain.txt")
    outer = [Point2[WorldXY].build(float.fromhex(x), float.fromhex(y)) for x, y in (line.split() for line in domain_lines[1 : 1 + int(domain_lines[0])])]
    return ToolRadius.build(float.fromhex(radius)), cuts, CentreDomain.build(outer)


def _timed(domain: CentreDomain, tool_radius: ToolRadius, cuts: Sequence[FullCircleSweep], audit: bool) -> tuple[CircleCoreReport, TimedCoreRun]:
    load = os.getloadavg()[0]
    started = time.perf_counter()
    report = run_circle_core(domain, tool_radius, cuts, filter_mode=FilterMode.LAZY, audit=audit)
    return report, TimedCoreRun(time.perf_counter() - started, report.phase_s, load)


def _distance_to_loop(point: tuple[float, float], loop: np.ndarray) -> float:
    """Binary64 distance from ``point`` to the closed polyline ``loop`` (reporting only)."""
    a, b = loop, np.roll(loop, -1, axis=0)
    ab = b - a
    t = np.clip(((point - a) * ab).sum(axis=1) / (ab * ab).sum(axis=1), 0.0, 1.0)
    return float(np.hypot(*(a + t[:, None] * ab - point).T).min())


def measure() -> CircleCoreRecord:
    """Run the core ``TIMING_RUNS`` times plus one audit run.

    Raises:
        CircleCoreRunsDisagreeError: the runs differ in decisions or witnesses.
    """
    tool_radius, cuts, domain = load_fixture()
    reports, runs = zip(*(_timed(domain, tool_radius, cuts, audit=False) for _ in range(TIMING_RUNS)))
    audited, audit_run = _timed(domain, tool_radius, cuts, audit=True)
    texts = {report.canonical_text() for report in (*reports, audited)}
    if len(texts) != 1:
        raise CircleCoreRunsDisagreeError(f"{len(texts)} distinct outcomes in {TIMING_RUNS} timed runs and one audit run")
    report = reports[0]
    loop = np.array([(float(p.x), float(p.y)) for p in domain.outer])
    r = float(tool_radius.value)
    in_target = [e for e in report.exposed if e.uncovered_in_target]
    points = [(float(e.uncovered[0]), float(e.uncovered[1])) for e in in_target]
    beyond = tuple(sorted(p for p in points if _distance_to_loop(p, loop) > r))
    return CircleCoreRecord(
        generated_by=GENERATED_BY,
        schema=SCHEMA,
        identity=machine_identity(),
        build=build_identity(),
        cuts=len(cuts),
        domain_vertices=len(domain.outer),
        counters=dict(report.counters),
        exposed=len(report.exposed),
        uncovered_in_target=len(in_target),
        beyond_connector_reach=beyond,
        runs=tuple(runs),
        median_s=statistics.median(run.seconds for run in runs),
        audit=audit_run,
    )


def render_markdown(record: CircleCoreRecord) -> str:
    """The docs table of one circle-core record.

    Raises:
        FallbackCountersError: see ``FALLBACK_COUNTERS``.
    """
    c, build = record.counters, record.build
    median_run = sorted(record.runs, key=lambda run: run.seconds)[len(record.runs) // 2]
    phases = ", ".join(f"{s:.2f}" for s in median_run.phase_s)
    runs = ", ".join(f"{run.seconds:.2f} @ {run.load_1min:.1f}" for run in record.runs)
    beyond = "; ".join(f"({x:.2f}, {y:.2f})" for x, y in record.beyond_connector_reach) or "none"
    if sum(c[name] for name in FALLBACK_COUNTERS) != c["exact_fallbacks"]:
        raise FallbackCountersError(f"exact_fallbacks={c['exact_fallbacks']} is not the sum of {FALLBACK_COUNTERS}")
    fallbacks = ", ".join(f"`{name}` {c[name]}" for name in FALLBACK_COUNTERS if c[name])
    lines = [
        f"<!-- {record.generated_by} -->",
        "",
        f"Circle-circle core (`run_circle_core`, LAZY) on the frozen spike fixture `monstera_circles.txt` ({record.cuts} cuts, "
        f"{record.domain_vertices} Ω vertices), commit `{build.commit[:12]}`{' (dirty tree)' if build.dirty else ''}, {build.recorded_at}, "
        f"{record.identity.cpu_brand}. Median of {len(record.runs)} runs on one core, each listed as `seconds @ 1-min load average`; "
        "wall clock under the recorded load, it does not transfer between machines or loads.",
        "",
        "| quantity | value |",
        "|---|---|",
        f"| boundary circles / candidate pairs / sub-arcs | {c['boundary_circles']} / {c['candidate_pairs']:,} / {c['sub_arcs']:,} |",
        f"| exposed edges | {record.exposed} |",
        f"| proven uncovered points in T | {record.uncovered_in_target}; farther than r from ∂Ω (beyond any connector): {len(record.beyond_connector_reach)}, at {beyond} |",
        f"| exact fallbacks | {c['exact_fallbacks']} ({fallbacks}) |",
        f"| time (median) | **{record.median_s:.2f} s**; runs {runs} |",
        f"| phases of the median run (crossings, sweep, witness, target) | {phases} s |",
        f"| audit run (every covered sub-arc re-witnessed exactly, raises on disagreement) | completed, {record.audit.seconds:.0f} s @ load {record.audit.load_1min:.1f} |",
    ]
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--json", type=pathlib.Path, default=JSON_PATH)
    parser.add_argument("--md", type=pathlib.Path, default=MD_PATH)
    args = parser.parse_args(argv)
    record = measure()
    args.json.write_text(record.to_json(), encoding="utf-8")
    args.md.write_text(render_markdown(record), encoding="utf-8")


if __name__ == "__main__":
    main()
