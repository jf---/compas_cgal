"""Byte-identity digests of the Held toolpath generators, and the generation time of each run.

For each workload in ``DIGEST_WORKLOADS`` the generator of
``benchmarks.held_toolpath_benchmark`` runs in a fresh process. Three SHA-256
digests are taken of the ``repr`` of what it produced:

- ``initial``: the initial placement result (``HypothesisFigure5Path`` with its
  placements and ``guide_progress``), captured from inside ``generate`` so the
  digest is of the path the benchmark generated, not of a re-implementation;
- ``circles``: the refined circles;
- ``connectors``: the connector transitions;
- ``entry`` (additive, 2026-11-04): the helical entry record
  (``benchmarks.held_helix_entry.entry_digest``). The six fields above are
  unchanged by it: a record without ``entry`` still parses, and ``--check``
  compares ``entry`` whenever either side carries one.

This is the serialisation the bookkeeping and native-clearance A/B proofs used
(``build/bookkeeping_ab/digest.py``): ``repr`` of frozen dataclasses prints
every float with ``float.__repr__`` (shortest round-trip, so a one-ulp change
changes the digest) and every ``Fraction`` exactly. A ``repr`` that carries a
memory address is not canonical and is refused.

``benchmarks/results/held_path_digests.json`` is written by this tool; do not
edit it. ``--check`` regenerates and fails loud on any difference, which is the
byte-identity proof for a change that must not move the path.
"""

from __future__ import annotations

import argparse
import dataclasses
import json
import re
import subprocess
import sys
from collections.abc import Callable
from collections.abc import Iterator
from collections.abc import Mapping
from contextlib import contextmanager
from dataclasses import dataclass
from functools import wraps
from pathlib import Path
from typing import Any
from typing import TypeVar

from benchmarks import held_toolpath_benchmark as toolpath_benchmark
from benchmarks.held_helix_entry import entry_digest
from benchmarks.performance_record import REPOSITORY
from tools.streaming_repr_digest import ReprCarriesMemoryAddressError
from tools.streaming_repr_digest import repr_sha256

SCHEMA = "held-path-digests/1"
DIGEST_PATH = REPOSITORY / "benchmarks" / "results" / "held_path_digests.json"
GENERATED_BY = "Generated by tools/held_path_digest.py; do not edit, run `pixi run held-path-digests` (`--check` to verify)."
DIGEST_WORKLOADS: tuple[str, ...] = (
    "figure5_refined",
    "figure8_crossed_skis_boundary",
    "figure8_upper_boundary",
    "figure8_monstera_boundary_qualified_corners",
)
# Prefix of the one stdout line a worker process reports its measurement on.
WORKER_MARKER = "HELD_PATH_DIGEST_RESULT "
_SHA256_HEX = re.compile(r"[0-9a-f]{64}")
# The generator entry points whose return value is the initial placement result.
_INITIAL_PATH_BUILDERS = ("build_figure5_approximate_path", "build_held_reference_path")
_DIGEST_FIELDS = ("initial", "circles", "connectors", "circle_count", "connector_count", "seam")
# The additive field: the helical entry's digest (optional in a record).
_ENTRY_FIELD = "entry"

T = TypeVar("T")


class HeldPathDigestError(Exception):
    """Base class of the Held path digest failures."""


class NonCanonicalReprError(HeldPathDigestError):
    """A digested value's ``repr`` carries a memory address, so it differs run to run."""


class MalformedDigestRecordError(HeldPathDigestError):
    """The digest record breaks its schema."""


class DigestMismatchError(HeldPathDigestError):
    """A regenerated digest differs from the recorded one."""


class InitialPathCaptureError(HeldPathDigestError):
    """The generator did not build exactly one initial placement result."""


class MissingWorkerResultError(HeldPathDigestError):
    """A worker process reported no measurement line."""


class WorkerProcessError(HeldPathDigestError):
    """A worker process exited non-zero."""


def canonical_digest(value: object) -> str:
    """SHA-256 hex digest of ``repr(value)``, streamed (``tools.streaming_repr_digest``): the string is never built.

    Raises:
        NonCanonicalReprError: the ``repr`` carries a memory address.
    """
    try:
        return repr_sha256(value)
    except ReprCarriesMemoryAddressError as error:
        raise NonCanonicalReprError(str(error)) from error


@dataclass(frozen=True)
class WorkloadDigest:
    """The digests and counts of one generated path.

    Attributes:
        initial: SHA-256 of the initial placement result's ``repr``.
        circles: SHA-256 of the refined circles' ``repr``.
        connectors: SHA-256 of the connector transitions' ``repr``.
        circle_count: Number of refined circles.
        connector_count: Number of connector transitions.
        seam: The ``Figure5SeamClosure`` value of the loop.
        entry: SHA-256 of the helical entry record, or None in a record
            written before the entry existed.
    """

    initial: str
    circles: str
    connectors: str
    circle_count: int
    connector_count: int
    seam: str
    entry: str | None = None

    @classmethod
    def from_raw(cls, workload: str, raw: object) -> WorkloadDigest:
        """Validate one workload's JSON object.

        Raises:
            MalformedDigestRecordError: a field is missing, extra, or of the wrong form.
        """
        if not isinstance(raw, dict) or set(raw) not in (set(_DIGEST_FIELDS), {*_DIGEST_FIELDS, _ENTRY_FIELD}):
            raise MalformedDigestRecordError(f"{workload}: fields must be exactly {_DIGEST_FIELDS}, optionally with {_ENTRY_FIELD!r}, got {raw!r}.")
        hashed = ("initial", "circles", "connectors", _ENTRY_FIELD) if _ENTRY_FIELD in raw else ("initial", "circles", "connectors")
        for name in hashed:
            if not isinstance(raw[name], str) or _SHA256_HEX.fullmatch(raw[name]) is None:
                raise MalformedDigestRecordError(f"{workload}: {name} is not a SHA-256 hex digest: {raw[name]!r}.")
        for name in ("circle_count", "connector_count"):
            if type(raw[name]) is not int or raw[name] < 0:
                raise MalformedDigestRecordError(f"{workload}: {name} is not a non-negative int: {raw[name]!r}.")
        if not isinstance(raw["seam"], str):
            raise MalformedDigestRecordError(f"{workload}: seam is not a string: {raw['seam']!r}.")
        return cls(**raw)


def _digest_json(digest: WorkloadDigest) -> dict[str, Any]:
    """One workload's JSON object: the six fields, plus ``entry`` when present."""
    body = dataclasses.asdict(digest)
    if body[_ENTRY_FIELD] is None:
        del body[_ENTRY_FIELD]
    return body


@dataclass(frozen=True)
class HeldPathDigests:
    """The committed digest record, one ``WorkloadDigest`` per workload."""

    workloads: Mapping[str, WorkloadDigest]

    def to_json(self) -> str:
        body = {
            "generated_by": GENERATED_BY,
            "schema": SCHEMA,
            "workloads": {name: _digest_json(self.workloads[name]) for name in sorted(self.workloads)},
        }
        return json.dumps(body, indent=2) + "\n"

    @classmethod
    def from_json(cls, text: str) -> HeldPathDigests:
        """Parse and validate a record.

        Raises:
            MalformedDigestRecordError: the document breaks the schema.
        """
        raw = json.loads(text)
        if not isinstance(raw, dict) or set(raw) != {"generated_by", "schema", "workloads"}:
            raise MalformedDigestRecordError(f"top-level keys must be generated_by, schema, workloads; got {sorted(raw) if isinstance(raw, dict) else raw!r}.")
        if raw["schema"] != SCHEMA:
            raise MalformedDigestRecordError(f"schema {raw['schema']!r} is not {SCHEMA!r}.")
        workloads = raw["workloads"]
        if not isinstance(workloads, dict) or not workloads:
            raise MalformedDigestRecordError("workloads must be a non-empty object.")
        return cls({name: WorkloadDigest.from_raw(name, entry) for name, entry in workloads.items()})


@dataclass(frozen=True)
class WorkloadMeasurement:
    """One fresh-process generation: its digests and its stage clocks.

    Attributes:
        workload: The ``held_toolpath_benchmark.GENERATORS`` key.
        digest: The digests of the generated path.
        generation_seconds: Sum of the stage clocks (case load and digesting excluded).
        stage_seconds: Wall-clock seconds per generator stage.
    """

    workload: str
    digest: WorkloadDigest
    generation_seconds: float
    stage_seconds: Mapping[str, float]

    def to_json_line(self) -> str:
        return json.dumps(
            {
                "workload": self.workload,
                "digest": _digest_json(self.digest),
                "generation_seconds": self.generation_seconds,
                "stage_seconds": dict(self.stage_seconds),
            }
        )

    @classmethod
    def from_json_line(cls, line: str) -> WorkloadMeasurement:
        raw = json.loads(line)
        return cls(
            workload=raw["workload"],
            digest=WorkloadDigest.from_raw(raw["workload"], raw["digest"]),
            generation_seconds=float(raw["generation_seconds"]),
            stage_seconds={str(name): float(seconds) for name, seconds in raw["stage_seconds"].items()},
        )


@contextmanager
def _capture_initial_paths() -> Iterator[list[object]]:
    """Record every initial placement result the benchmark generators build, unchanged."""
    captured: list[object] = []
    originals: dict[str, Callable[..., Any]] = {name: getattr(toolpath_benchmark, name) for name in _INITIAL_PATH_BUILDERS}

    def recording(builder: Callable[..., T]) -> Callable[..., T]:
        @wraps(builder)
        def record(*args: Any, **kwargs: Any) -> T:
            result = builder(*args, **kwargs)
            captured.append(result)
            return result

        return record

    for name, builder in originals.items():
        setattr(toolpath_benchmark, name, recording(builder))
    try:
        yield captured
    finally:
        for name, builder in originals.items():
            setattr(toolpath_benchmark, name, builder)


def measure_workload(workload: str) -> WorkloadMeasurement:
    """Generate one workload in this process and digest it.

    Raises:
        InitialPathCaptureError: the generator did not build exactly one initial path.
        NonCanonicalReprError: a generated value has no canonical ``repr``.
    """
    with _capture_initial_paths() as captured:
        path = toolpath_benchmark.generate(workload)
    if len(captured) != 1:
        raise InitialPathCaptureError(f"{workload}: expected one initial placement result, captured {len(captured)}.")
    digest = WorkloadDigest(
        initial=canonical_digest(captured[0]),
        circles=canonical_digest(path.circles),
        connectors=canonical_digest(path.transitions),
        circle_count=len(path.circles),
        connector_count=len(path.transitions),
        seam=path.connectors.seam.value,
        entry=entry_digest(path.entry),
    )
    return WorkloadMeasurement(workload, digest, path.generation_seconds, dict(path.stage_seconds))


def parse_worker_output(stdout: str) -> WorkloadMeasurement:
    """The measurement on the worker's marker line.

    Raises:
        MissingWorkerResultError: no line carries ``WORKER_MARKER``.
    """
    lines = [line for line in stdout.splitlines() if line.startswith(WORKER_MARKER)]
    if len(lines) != 1:
        raise MissingWorkerResultError(f"expected one {WORKER_MARKER.strip()} line, found {len(lines)}; stdout tail:\n{stdout[-2000:]}")
    return WorkloadMeasurement.from_json_line(lines[0][len(WORKER_MARKER) :])


def measure_in_fresh_process(workload: str) -> WorkloadMeasurement:
    """Generate one workload in a fresh interpreter (same executable and environment).

    Raises:
        WorkerProcessError: the worker exited non-zero.
        MissingWorkerResultError: the worker reported no measurement.
    """
    completed = subprocess.run(
        [sys.executable, "-m", "tools.held_path_digest", "--worker", workload],
        cwd=REPOSITORY,
        capture_output=True,
        text=True,
        check=False,
    )
    if completed.returncode != 0:
        raise WorkerProcessError(f"{workload}: worker exited {completed.returncode}; stderr tail:\n{completed.stderr[-4000:]}")
    return parse_worker_output(completed.stdout)


def mismatches(recorded: HeldPathDigests, current: HeldPathDigests, workloads: tuple[str, ...] | None = None) -> list[str]:
    """Every difference between the recorded and current digests, over ``workloads`` (all recorded by default)."""
    names = tuple(recorded.workloads) if workloads is None else workloads
    found: list[str] = []
    for name in names:
        was, now = recorded.workloads.get(name), current.workloads.get(name)
        if was is None or now is None:
            found.append(f"{name}: {'not recorded' if was is None else 'not measured'}.")
            continue
        fields = _DIGEST_FIELDS if was.entry is None and now.entry is None else (*_DIGEST_FIELDS, _ENTRY_FIELD)
        for field in fields:
            before, after = getattr(was, field), getattr(now, field)
            if before != after:
                found.append(f"{name}: {field} {after!r} != recorded {before!r}.")
    return found


def require_identical(recorded: HeldPathDigests, current: HeldPathDigests, workloads: tuple[str, ...] | None = None) -> None:
    """Raises:
    DigestMismatchError: any digest or count differs.
    """
    found = mismatches(recorded, current, workloads)
    if found:
        raise DigestMismatchError("Held path digests differ from the record:\n" + "\n".join(found))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--workloads", nargs="+", default=list(DIGEST_WORKLOADS), choices=list(toolpath_benchmark.GENERATORS))
    parser.add_argument("--output", type=Path, default=DIGEST_PATH)
    parser.add_argument("--check", action="store_true", help="regenerate and fail on any difference from --output; write nothing")
    parser.add_argument("--worker", choices=list(toolpath_benchmark.GENERATORS), help=argparse.SUPPRESS)
    args = parser.parse_args()
    if args.worker is not None:
        print(WORKER_MARKER + measure_workload(args.worker).to_json_line(), flush=True)
        return
    workloads: tuple[str, ...] = tuple(args.workloads)
    measured: dict[str, WorkloadDigest] = {}
    for name in workloads:
        measurement = measure_in_fresh_process(name)
        measured[name] = measurement.digest
        digest = measurement.digest
        print(
            f"{name:<44} {measurement.generation_seconds:8.2f} s  circles {digest.circle_count:>5}  "
            f"initial {digest.initial[:12]}  circles {digest.circles[:12]}  connectors {digest.connectors[:12]}",
            flush=True,
        )
    current = HeldPathDigests(measured)
    if args.check:
        require_identical(HeldPathDigests.from_json(args.output.read_text(encoding="utf-8")), current, workloads)
        print(f"IDENTICAL {args.output} ({', '.join(workloads)})")
        return
    if args.output.is_file():
        recorded = HeldPathDigests.from_json(args.output.read_text(encoding="utf-8"))
        current = HeldPathDigests({**recorded.workloads, **measured})
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(current.to_json(), encoding="utf-8")
    print(f"RECORD {args.output}")


if __name__ == "__main__":
    main()
