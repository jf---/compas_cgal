@dataclass(frozen=True)
class CircleSweep:
    """One emitted machining circle: guide centre and radius, and the entry (contact) point."""

    cx: float
    cy: float
    guide_radius: float
    entry_x: float
    entry_y: float


@dataclass(frozen=True)
class SegmentSweep:
    """One non-degenerate connector segment, owned by the circle the connector leaves."""

    owner: int
    x0: float
    y0: float
    x1: float
    y1: float


@dataclass(frozen=True, eq=False)
class ReplayWorkload:
    """The sweeps an actual-stock replay inserts, in emission order, and the decision's constants."""

    name: str
    polygon: NDArray[np.float64]
    tool_radius: float
    cap_chord_ratio: float
    circles: tuple[CircleSweep, ...]
    segments: tuple[SegmentSweep, ...]
    generation_s: float

    @classmethod
    def build(cls, workload: str) -> ReplayWorkload:
        """Generate ``workload`` and extract its sweeps (generation time is process CPU)."""
        start = time.process_time()
        path = generate(workload)
        return cls.from_path(path, time.process_time() - start)

    @classmethod
    def from_path(cls, path: GeneratedToolpath, generation_s: float) -> ReplayWorkload:
        case = path.case
        segments: list[SegmentSweep] = []
        for owner, (_first, _second, transition) in enumerate(connector_pairs(path.circles, path.transitions)):
            for a, b in zip(transition.samples, transition.samples[1:]):
                if a != b:
                    segments.append(SegmentSweep(owner, float(a.x), float(a.y), float(b.x), float(b.y)))
        circles = tuple(CircleSweep(float(c.center.x), float(c.center.y), float(c.radius.value), float(c.contact_point.x), float(c.contact_point.y)) for c in path.circles)
        polygon = np.array([(float(p.x), float(p.y), 0.0) for p in case.projection.points], dtype=np.float64)
        return cls(
            name=path.workload,
            polygon=polygon,
            tool_radius=float(case.tool_radius.value),
            cap_chord_ratio=_stock_2.cap_chord_ratio(math.radians(float(case.tea_cap))),
            circles=circles,
            segments=tuple(segments),
            generation_s=generation_s,
        )

    def segments_by_owner(self) -> list[list[SegmentSweep]]:
        owned: list[list[SegmentSweep]] = [[] for _ in self.circles]
        for segment in self.segments:
            owned[segment.owner].append(segment)
        return owned

    def fresh_stock(self) -> _stock_2.Stock2:
        return _stock_2.Stock2(self.polygon, [])

    def subtract_circle(self, stock: _stock_2.Stock2, circle: CircleSweep) -> None:
        stock.subtract_circle_sweep_local(circle.cx, circle.cy, circle.guide_radius, self.tool_radius)

    def subtract_segment(self, stock: _stock_2.Stock2, segment: SegmentSweep) -> None:
        stock.subtract_line_sweep_local(segment.x0, segment.y0, segment.x1, segment.y1, self.tool_radius)

    def exceeded(self, stock: _stock_2.Stock2, index: int) -> bool:
        """The generator's decision: some loop station of circle ``index`` exceeds the cap on ``stock``."""
        c = self.circles[index]
        return bool(
            _stock_2.engagement_circle_exceeded(
                stock, c.cx, c.cy, c.guide_radius, c.entry_x, c.entry_y, False, loop_parameters(), self.tool_radius, self.cap_chord_ratio, NO_GAP_CLOSURE
            )
        )

    def prefixes(self, stock: _stock_2.Stock2, index: int) -> list[tuple[float, float, bool]]:
        c = self.circles[index]
        samples = _stock_2.engagement_circle_prefixes(
            stock, c.cx, c.cy, c.guide_radius, c.entry_x, c.entry_y, False, loop_parameters(), self.tool_radius, self.cap_chord_ratio, NO_GAP_CLOSURE
        )
        return [(float(a), float(b), bool(e)) for a, b, e in samples]


