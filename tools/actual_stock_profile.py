@dataclass(frozen=True)
class BudgetRun:
    """One fresh-process engine replay of a workload, stopped once its CPU passed the budget."""

    workload: str
    budget: EngineBudget
    circles: int
    segments: int
    sweeps_done: int
    queries_done: int
    sweep_cpu_s: CpuS
    query_cpu_s: CpuS
    wall_s: float
    completed: bool
    exceeded_queries: int
    generation_s: float
    load_before: LoadAverage
    load_after: LoadAverage

    @property
    def sweeps(self) -> int:
        return self.circles + self.segments

    @property
    def total_cpu_s(self) -> CpuS:
        return CpuS(self.sweep_cpu_s + self.query_cpu_s)

    @property
    def per_sweep_ms(self) -> CpuMs:
        return CpuMs(MS_PER_S * self.sweep_cpu_s / max(self.sweeps_done, 1))

    @property
    def per_query_ms(self) -> CpuMs:
        return CpuMs(MS_PER_S * self.query_cpu_s / max(self.queries_done, 1))

    def failures(self) -> list[str]:
        """Every budget line this run breaks; empty iff the run is within budget."""
        out: list[str] = []
        if not self.completed or self.total_cpu_s > self.budget.total_s:
            out.append(
                f"total {self.total_cpu_s:.2f} s CPU > {self.budget.total_s} s, {self.sweeps_done:,}/{self.sweeps:,} sweeps and {self.queries_done:,}/{self.circles:,} queries"
                + ("" if self.completed else " (stopped at the budget)")
            )
        if self.budget.per_sweep_ms is not None and self.per_sweep_ms > self.budget.per_sweep_ms:
            out.append(f"{self.per_sweep_ms:.2f} ms per sweep > {self.budget.per_sweep_ms} ms")
        if self.budget.per_query_ms is not None and self.per_query_ms > self.budget.per_query_ms:
            out.append(f"{self.per_query_ms:.2f} ms per query > {self.budget.per_query_ms} ms")
        return out

    def describe(self) -> str:
        load = " / ".join(f"{v:.1f}" for v in self.load_before)
        return (
            f"{self.workload}: sweeps {self.sweeps_done:,}/{self.sweeps:,} in {self.sweep_cpu_s:.2f} s ({self.per_sweep_ms:.2f} ms each), "
            f"queries {self.queries_done:,}/{self.circles:,} in {self.query_cpu_s:.2f} s ({self.per_query_ms:.2f} ms each), "
            f"total {self.total_cpu_s:.2f} s CPU, wall {self.wall_s:.2f} s, completed {self.completed}, load avg before {load}"
        )


@dataclass(frozen=True)
class ProfileRecord:
    generated_by: str
    schema: str
    machine: MachineIdentity
    build: BuildIdentity
    workload: str
    circles: int
    segments: int
    stations: int
    generation_s: float
    load_start: LoadAverage
    load_end: LoadAverage
    sequential: tuple[SequentialRow, ...]
    windows: tuple[WindowRow, ...]
    budget_runs: tuple[BudgetRun, ...]

    def to_json(self) -> str:
        return json.dumps(_encode(self), indent=1) + "\n"

    @classmethod
    def from_json(cls, text: str) -> ProfileRecord:
        """Load a recorded profile.

        Raises:
            MalformedProfileRecordError: the JSON breaks this schema.
        """
        record = cast(ProfileRecord, _decode(ProfileRecord, json.loads(text), "$"))
        if record.schema != SCHEMA:
            raise MalformedProfileRecordError(f"schema {record.schema!r}, expected {SCHEMA!r}")
        return record


def _encode(value: object) -> object:
    if dataclasses.is_dataclass(value) and not isinstance(value, type):
        return {f.name: _encode(getattr(value, f.name)) for f in dataclasses.fields(value)}
    if isinstance(value, tuple):
        return [_encode(v) for v in value]
    if isinstance(value, float):
        return round(value, 4)
    return value


def _decode(tp: object, raw: object, where: str) -> object:
    """Rebuild a value of annotated type ``tp`` from its JSON form, refusing any mismatch."""
    supertype = getattr(tp, "__supertype__", None)
    if supertype is not None:
        return _decode(supertype, raw, where)
    if isinstance(tp, type) and dataclasses.is_dataclass(tp):
        if not isinstance(raw, dict):
            raise MalformedProfileRecordError(f"{where}: expected an object for {tp.__name__}")
        hints = typing.get_type_hints(tp)
        names = [f.name for f in dataclasses.fields(tp)]
        if set(raw) != set(names):
            raise MalformedProfileRecordError(f"{where}: fields {sorted(raw)} != {sorted(names)}")
        return tp(**{n: _decode(hints[n], raw[n], f"{where}.{n}") for n in names})
    origin, args = typing.get_origin(tp), typing.get_args(tp)
    if origin is types.UnionType or origin is typing.Union:
        if raw is None and type(None) in args:
            return None
        (inner,) = (a for a in args if a is not type(None))
        return _decode(inner, raw, where)
    if origin is tuple:
        if not isinstance(raw, list):
            raise MalformedProfileRecordError(f"{where}: expected an array")
        if len(args) == 2 and args[1] is Ellipsis:
            return tuple(_decode(args[0], v, f"{where}[{i}]") for i, v in enumerate(raw))
        if len(raw) != len(args):
            raise MalformedProfileRecordError(f"{where}: expected {len(args)} items, got {len(raw)}")
        return tuple(_decode(a, v, f"{where}[{i}]") for i, (a, v) in enumerate(zip(args, raw)))
    if tp is float and isinstance(raw, (int, float)) and not isinstance(raw, bool):
        return float(raw)
    if tp in (int, str, bool) and type(raw) is tp:
        return raw
    raise MalformedProfileRecordError(f"{where}: {raw!r} is not a {tp}")


def _cpu_ms(start: float) -> CpuMs:
    return CpuMs(MS_PER_S * (time.process_time() - start))


def query_circle(workload: ReplayWorkload, stock: _stock_2.Stock2, index: int) -> StationQuery:
    """Cold decision (first query after a mutation), warm decision, warm prefixes of circle ``index``.

    Raises:
        ColdWarmDisagreementError: the cached locator changed the verdict.
    """
    start = time.process_time()
    cold = workload.exceeded(stock, index)
    cold_ms = _cpu_ms(start)
    start = time.process_time()
    warm = workload.exceeded(stock, index)
    warm_ms = _cpu_ms(start)
    start = time.process_time()
    samples = workload.prefixes(stock, index)
    prefixes_ms = _cpu_ms(start)
    if cold != warm:
        raise ColdWarmDisagreementError(f"{workload.name} circle {index}: cold {cold}, warm {warm}")
    max_run = Degrees(max(math.degrees(sample[1]) for sample in samples))
    return StationQuery(bool(cold), max_run, cold_ms, warm_ms, prefixes_ms)


def run_sequential(workload: ReplayWorkload, limit: int) -> tuple[SequentialRow, ...]:
    """Emission-order replay of the first ``limit`` circles, each queried on the stock before it."""
    stock = workload.fresh_stock()
    owned = workload.segments_by_owner()
    rows: list[SequentialRow] = []
    for index in range(min(limit, len(workload.circles))):
        halfedges = stock.arrangement_stats()[1]
        query = query_circle(workload, stock, index)
        start = time.process_time()
        workload.subtract_circle(stock, workload.circles[index])
        circle_ms = _cpu_ms(start)
        start = time.process_time()
        for segment in owned[index]:
            workload.subtract_segment(stock, segment)
        connector_ms = _cpu_ms(start)
        rows.append(SequentialRow(index, int(halfedges), circle_ms, len(owned[index]), connector_ms, query))
    return tuple(rows)


def run_windows(workload: ReplayWorkload, stride: int) -> tuple[WindowRow, ...]:
    """Exact, last-16 and last-1 window stocks of every ``stride``-th circle.

    Raises:
        BoundBreakError: the exact window exceeds where a last-m window does not.
    """
    # Function-scope import: the certificate module imports ``ReplayWorkload``
    # from this module, so a module-level import would be circular.
    from benchmarks.held_actual_stock_last16 import Last16Oracle

    oracle = Last16Oracle(workload)

    def window_stock(index: int, last: int | None) -> WindowStock:
        # The gated certificate's own window, exact selection and global overlay: one implementation.
        start = time.process_time()
        window = oracle.window(index)
        events, _omitted = oracle.select(index, window, last)
        stock = oracle.build_stock(index, window, events)
        build_ms = _cpu_ms(start)
        return WindowStock(len(events), int(stock.arrangement_stats()[1]), build_ms, query_circle(workload, stock, index))

    rows: list[WindowRow] = []
    for index in range(1, len(workload.circles), stride):
        row = WindowRow(index, window_stock(index, None), window_stock(index, LAST_M), window_stock(index, LAST_ONE))
        if row.exact.query.exceeded and not (row.last16.query.exceeded and row.last1.query.exceeded):
            raise BoundBreakError(f"{workload.name} circle {index}: exact exceeded, last-16 {row.last16.query.exceeded}, last-1 {row.last1.query.exceeded}")
        rows.append(row)
    return tuple(rows)


def run_budget(workload: ReplayWorkload, budget: EngineBudget) -> BudgetRun:
    """Full emission-order replay with one decision per circle, stopped once its CPU time passes ``budget.total_s``."""
    owned = workload.segments_by_owner()
    load_before = os.getloadavg()
    wall_start = time.perf_counter()
    stock = workload.fresh_stock()
    sweep_s = query_s = 0.0
    sweeps = queries = exceeded = 0

    def over() -> bool:
        return sweep_s + query_s > budget.total_s

    for index, circle in enumerate(workload.circles):
        start = time.process_time()
        exceeded += workload.exceeded(stock, index)
        query_s += time.process_time() - start
        queries += 1
        if over():
            break
        start = time.process_time()
        workload.subtract_circle(stock, circle)
        sweep_s += time.process_time() - start
        sweeps += 1
        if over():
            break
        for segment in owned[index]:
            start = time.process_time()
            workload.subtract_segment(stock, segment)
            sweep_s += time.process_time() - start
            sweeps += 1
            if over():
                break
        if over():
            break
    completed = queries == len(workload.circles) and sweeps == len(workload.circles) + len(workload.segments)
    return BudgetRun(
        workload=workload.name,
        budget=budget,
        circles=len(workload.circles),
        segments=len(workload.segments),
        sweeps_done=sweeps,
        queries_done=queries,
        sweep_cpu_s=CpuS(sweep_s),
        query_cpu_s=CpuS(query_s),
        wall_s=time.perf_counter() - wall_start,
        completed=completed,
        exceeded_queries=exceeded,
        generation_s=workload.generation_s,
        load_before=load_before,
        load_after=os.getloadavg(),
    )


def measure_budget_in_fresh_process(workload: str) -> BudgetRun:
    """Run ``run_budget`` for ``workload`` in a fresh interpreter (inherits the editable-build environment).

    Raises:
        BudgetWorkerError: the worker exited non-zero.
        MissingBudgetResultError: the worker printed no result line.
    """
    done = subprocess.run([sys.executable, "-m", "tools.actual_stock_profile", "--budget-worker", workload], cwd=REPOSITORY, capture_output=True, text=True)
    if done.returncode != 0:
        raise BudgetWorkerError(f"budget worker for {workload} exited {done.returncode}:\n{done.stderr[-4000:]}")
    lines = [line for line in done.stdout.splitlines() if line.startswith(WORKER_MARKER)]
    if len(lines) != 1:
        raise MissingBudgetResultError(f"budget worker for {workload} printed {len(lines)} result lines:\n{done.stdout[-4000:]}")
    return cast(BudgetRun, _decode(BudgetRun, json.loads(lines[0][len(WORKER_MARKER) :]), "$"))


def _mean(values: Sequence[float]) -> float:
    return float(np.mean(np.asarray(values, dtype=np.float64)))


def _quantile(values: Sequence[float], q: float) -> float:
    return float(np.quantile(np.asarray(values, dtype=np.float64), q))


def _band_label(lo: int, hi: int | None) -> str:
    return f"{lo:,}–{hi:,}" if hi is not None else f"≥ {lo:,}"


def _load(la: LoadAverage) -> str:
    return " / ".join(f"{v:.0f}" for v in la)


def render_markdown(record: ProfileRecord) -> str:
    """The docs tables of one recorded profile."""
    b, m = record.build, record.machine
    out = [
        f"<!-- {record.generated_by} -->",
        "",
        f"Process CPU time of single-threaded native calls, commit `{b.commit[:12]}`{' (dirty tree)' if b.dirty else ''}, {b.recorded_at}, "
        f"{m.cpu_brand}. Load average at start {_load(record.load_start)}, at end {_load(record.load_end)} (1 / 5 / 15 min); "
        f"above the core count the absolute values are inflated, ratios hold. Profile workload `{record.workload}`: "
        f"{record.circles:,} circles, {record.segments:,} connector segments, {record.stations} loop stations per query.",
        "",
        "**Engine budget, measured** (full replay + one decision per circle, fresh process, stopped once over budget):",
        "",
        "| workload | sweeps (circles + segments) | queries | budget | done | sweep CPU | query CPU | per sweep | per query | load before | verdict |",
        "| --- | ---: | ---: | --- | --- | ---: | ---: | ---: | ---: | --- | --- |",
    ]
    split = (MONSTERA_PER_SWEEP_MS, MONSTERA_PER_QUERY_MS)
    for run in record.budget_runs:
        bud = run.budget
        per = "" if bud.per_sweep_ms is None else f" (≤ {bud.per_sweep_ms} ms/sweep, ≤ {bud.per_query_ms} ms/query)"
        verdict = "within" if not run.failures() else "**over**"
        out.append(
            f"| `{run.workload}` | {run.sweeps:,} ({run.circles:,} + {run.segments:,}) | {run.circles:,} | ≤ {bud.total_s} s{per} | "
            f"{run.sweeps_done:,} sweeps, {run.queries_done:,} queries | {run.sweep_cpu_s:.2f} s | {run.query_cpu_s:.2f} s | "
            f"{run.per_sweep_ms:.2f} ms ({run.per_sweep_ms / split[0]:.0f}×) | "
            f"{run.per_query_ms:.2f} ms ({run.per_query_ms / split[1]:.0f}×) | {_load(run.load_before)} | {verdict} |"
        )
    out += [
        "",
        "Per-item ratios are against the Monstera split; a run stopped at the budget reports the means of its prefix, where the arrangement is still small.",
        "",
        f"**Sequential replay** (emission order, first {len(record.sequential):,} circles; the arrangement reaches "
        f"{max(r.halfedges for r in record.sequential):,} halfedges). CPU ms, means per circle:",
        "",
        "| halfedges before circle | n | circle subtract | connector subtract | query cold | query warm | locator rebuild (cold − warm) | per station (prefixes / stations) |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for lo, hi in HALFEDGE_BANDS:
        rows = [r for r in record.sequential if r.halfedges >= lo and (hi is None or r.halfedges < hi)]
        if not rows:
            continue
        cold = _mean([r.query.exceeded_cold_ms for r in rows])
        warm = _mean([r.query.exceeded_warm_ms for r in rows])
        out.append(
            f"| {_band_label(lo, hi)} | {len(rows)} | {_mean([r.circle_subtract_ms for r in rows]):.1f} | {_mean([r.connector_subtract_ms for r in rows]):.1f} | "
            f"{cold:.1f} | {warm:.1f} | {cold - warm:.1f} | {_mean([r.query.prefixes_warm_ms for r in rows]) / record.stations:.2f} |"
        )
    windows = record.windows
    views = (("exact (every prior sweep meeting the window)", "exact"), (f"last-{LAST_M} bound", "last16"), (f"last-{LAST_ONE} bound", "last1"))
    out += [
        "",
        f"**Windowed local stocks** ({len(windows)} sampled circles, every {WINDOW_STRIDE}th, the last-16 certificate's windows, exact selection and global overlay). Medians:",
        "",
        "| local stock | sweeps | halfedges | build (clip + sweeps) | per sweep | query warm | per station | decision exceeded |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    per_sweep_last1 = math.nan
    for label, key in views:
        stocks = [cast(WindowStock, getattr(r, key)) for r in windows]
        build = _quantile([s.build_ms for s in stocks], 0.5)
        per_sweep = _quantile([s.build_ms / max(s.sweeps, 1) for s in stocks], 0.5)
        if key == "last1":
            per_sweep_last1 = per_sweep
        out.append(
            f"| {label} | {_quantile([s.sweeps for s in stocks], 0.5):g} | {_quantile([s.halfedges for s in stocks], 0.5):g} | {build:.1f} ms | {per_sweep:.2f} ms | "
            f"{_quantile([s.query.exceeded_warm_ms for s in stocks], 0.5):.1f} ms | {_quantile([s.query.prefixes_warm_ms for s in stocks], 0.5) / record.stations:.2f} ms | "
            f"{sum(s.query.exceeded for s in stocks)} / {len(stocks)} |"
        )
    gap = [r.last16.query.max_run_deg - r.exact.query.max_run_deg for r in windows]
    overturned16 = sum(r.last16.query.exceeded and not r.exact.query.exceeded for r in windows)
    overturned1 = sum(r.last1.query.exceeded and not r.exact.query.exceeded for r in windows)
    warm_query = _quantile([r.exact.query.exceeded_warm_ms for r in windows], 0.5)
    monstera = next((run for run in record.budget_runs if run.workload == MONSTERA), None)
    out += [
        "",
        f"**Last-{LAST_M} bound vs exact** (same windows): max-run gap p50 {_quantile(gap, 0.5):.1f}°, p90 {_quantile(gap, 0.9):.1f}°, max {max(gap):.1f}°; "
        f"bound breaks 0 (checked, a break raises); refusals the exact stock overturns: last-{LAST_M} {overturned16}, last-{LAST_ONE} {overturned1}.",
    ]
    if monstera is not None:
        projected = (monstera.sweeps * per_sweep_last1 + monstera.circles * warm_query) / MS_PER_S
        out += [
            "",
            f"**Labelled-engine projection with today's constants** (about one small-arrangement sweep cost per sweep, one warm query per circle): "
            f"Monstera {monstera.sweeps:,} × {per_sweep_last1:.2f} ms + {monstera.circles:,} × {warm_query:.1f} ms ≈ {projected:.0f} s CPU at this load, "
            f"against ≤ {monstera.budget.total_s} s.",
        ]
    return "\n".join(out) + "\n"


def profile(sequential_circles: int, window_stride: int) -> ProfileRecord:
    load_start = os.getloadavg()
    budget_runs = tuple(measure_budget_in_fresh_process(name) for name in ENGINE_BUDGETS)
    workload = ReplayWorkload.build(PROFILE_WORKLOAD)
    sequential = run_sequential(workload, sequential_circles)
    windows = run_windows(workload, window_stride)
    return ProfileRecord(
        generated_by=GENERATED_BY,
        schema=SCHEMA,
        machine=machine_identity(),
        build=build_identity(),
        workload=workload.name,
        circles=len(workload.circles),
        segments=len(workload.segments),
        stations=len(loop_parameters()),
        generation_s=workload.generation_s,
        load_start=load_start,
        load_end=os.getloadavg(),
        sequential=sequential,
        windows=windows,
        budget_runs=budget_runs,
    )


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--json", type=Path, default=JSON_PATH)
    parser.add_argument("--md", type=Path, default=MD_PATH)
    parser.add_argument("--sequential-circles", type=int, default=SEQUENTIAL_CIRCLES)
    parser.add_argument("--window-stride", type=int, default=WINDOW_STRIDE)
    parser.add_argument("--render", action="store_true", help="re-render the markdown from the recorded JSON, measure nothing")
    parser.add_argument("--budget-worker", metavar="WORKLOAD", choices=list(ENGINE_BUDGETS), help="internal: one budget run, printed on the marker line")
    args = parser.parse_args(argv)
    if args.budget_worker:
        run = run_budget(ReplayWorkload.build(args.budget_worker), ENGINE_BUDGETS[args.budget_worker])
        print(WORKER_MARKER + json.dumps(_encode(run)), flush=True)
        return
    if args.render:
        record = ProfileRecord.from_json(args.json.read_text(encoding="utf-8"))
    else:
        record = profile(args.sequential_circles, args.window_stride)
        args.json.write_text(record.to_json(), encoding="utf-8")
    args.md.write_text(render_markdown(record), encoding="utf-8")
    print(render_markdown(record))


if __name__ == "__main__":
    main()
