"""Actual-stock replay cost profile and engine budget measurement (stage S0 of the actual-stock engine).

Today's engine is ``_stock_2.Stock2`` mutated by local sweep surgery
(``subtract_circle_sweep_local``, ``subtract_line_sweep_local``) and queried
by ``engagement_circle_exceeded`` / ``engagement_circle_prefixes`` at the
gate's 45 loop stations. This tool measures where that engine's time goes on
a generated Held path, with the existing native API only:

- **sequential**: replay in emission order (query circle i on the stock as it
  stands before circle i, then subtract circle i and connector i), first
  ``--sequential-circles`` circles. Per circle: halfedges, circle and
  connector subtraction, the first query after a mutation (COLD: builds the
  point locator), the same query again (WARM), and the prefixes (WARM).
  cold - warm is the locator rebuild; warm / stations is the station cost.
- **windows**: every ``--window-stride``-th circle, three window stocks built
  by the last-16 certificate itself (``Last16Oracle``: its clip disk, admitted
  by the exact station-containment proof, its exact sweep omission, its global
  overlay): EXACT (every prior sweep not proven exactly to miss the window,
  equal to the sequential replay on what the decision reads), LAST-16 and
  LAST-1 (only sweeps owned by circles i-m .. i-1). An
  exceeded EXACT must be exceeded on every last-m (Omega minus a subset of
  the sweeps is a superset); a break raises ``BoundBreakError``.
- **budget**: the full replay plus one decision query per circle, in a fresh
  process per workload, aborted as soon as its CPU time passes the workload's
  engine budget (the verdict is then certain without finishing).

Times are process CPU seconds of single-threaded native calls. The load
average is recorded at both ends and with every budget run.

``benchmarks/results/actual_stock_profile.{json,md}`` are written by this
tool; do not edit them. ``--render`` re-renders the markdown from the
recorded JSON without measuring.
"""

