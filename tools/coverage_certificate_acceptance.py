SCHEMA = "coverage-certificate-acceptance/1"
JSON_PATH = REPOSITORY / "benchmarks/results/coverage_certificate_acceptance.json"
MD_PATH = REPOSITORY / "benchmarks/results/coverage_certificate_acceptance.md"
GENERATED_BY = "Generated by tools/coverage_certificate_acceptance.py; do not edit, run `pixi run coverage-certificate-acceptance`."
TIMING_RUNS = 3
MONSTERA = "figure8_monstera_boundary_qualified_corners"
MONSTERA_REPAIRED = f"{MONSTERA}_repaired"
WORKLOADS: tuple[str, ...] = ("figure5_refined", "figure8_crossed_skis_boundary", "figure8_upper_boundary", MONSTERA, MONSTERA_REPAIRED)


class CoverageCertificateAcceptanceError(BenchmarkError):
    """Base error of the coverage-certificate acceptance tool."""


class CertificateRunsDisagreeError(CoverageCertificateAcceptanceError):
    """Two runs of the certificate on one input gave different verdicts or witnesses."""


class RegionAccountingError(CoverageCertificateAcceptanceError):
    """The native region count does not decompose into cuts, target vertex disks and connector regions."""


@dataclass(frozen=True)
class TimedRun:
    """One facade run: wall seconds and the 1-minute load average read just before it."""

    seconds: float
    load_1min: float


@dataclass(frozen=True)
class RepairLedger:
    """Reporting summary of the select-certify-repair stage."""

    emitted_before: int
    emitted_after: int
    inserted_sources: tuple[int, ...]
    rounds: int
    certificate_runs: int
    repair_s: float
    certificate_s: float


@dataclass(frozen=True)
class WorkloadCertificate:
    """The certificate on one generated path.

    ``connector_regions`` is ``region_count - cuts - domain_vertices``: the native
    region set is the cut circles, the merged connector capsules (end disks and
    rectangles) and one target vertex disk per centre-domain vertex
    (``coverage_certificate_2/certificate_2.cpp``, ``run_certificate``).
    """

    workload: str
    generation_s: float
    cuts: int
    connectors: int
    domain_vertices: int
    region_count: int
    connector_regions: int
    piece_count: int
    edge_count: int
    covered: bool
    witnesses: int
    undecided: int
    clusters: tuple[WitnessCluster, ...]
    runs: tuple[TimedRun, ...]
    median_s: float
    native_phase_s: tuple[float, float, float, float]
    repair: RepairLedger | None = None


@dataclass(frozen=True)
class AcceptanceRecord:
    generated_by: str
    schema: str
    identity: MachineIdentity
    build: BuildIdentity
    timing_runs: int
    cluster_link_mm: float
    workloads: tuple[WorkloadCertificate, ...]

    def to_json(self) -> str:
        return json.dumps(dataclasses.asdict(self), indent=2) + "\n"


def _witness_key(witnesses: Sequence[UncoveredWitness]) -> tuple[tuple[str, int, str, str], ...]:
    return tuple((w.piece_kind.name, w.region_index, str(w.uncovered_point[0]), str(w.uncovered_point[1])) for w in witnesses)


def certify(
    workload: str,
    generation_s: float,
    boundary: tuple[Point2[WorldXY], ...],
    circles: tuple[Figure5CounterclockwiseCircle, ...],
    tool_radius: ToolRadius,
    repair: RepairLedger | None = None,
) -> WorkloadCertificate:
    """Certify one closed path ``TIMING_RUNS`` times through the facade, then once natively for the region counts.

    Raises:
        CertificateRunsDisagreeError: the runs disagree on verdict or witnesses.
        RegionAccountingError: see ``WorkloadCertificate``.
    """
    domain = CentreDomain.build(list(boundary))
    cuts, connectors = path_sweeps(domain, boundary, circles)
    runs: list[TimedRun] = []
    outcomes: list[tuple[tuple[str, int, str, str], ...]] = []
    witnesses: tuple[UncoveredWitness, ...] = ()
    undecided = 0
    for _ in range(TIMING_RUNS):
        load = os.getloadavg()[0]
        started = time.perf_counter()
        try:
            CoverageCertificate.build(domain, tool_radius, cuts, connectors)
            witnesses, undecided = (), 0
        except UncoveredPocketError as error:
            witnesses, undecided = tuple(error.witnesses), error.undecided_edge_count
        runs.append(TimedRun(time.perf_counter() - started, load))
        outcomes.append(_witness_key(witnesses))
    if len(set(outcomes)) != 1:
        raise CertificateRunsDisagreeError(f"{workload}: {len(set(outcomes))} distinct outcomes in {TIMING_RUNS} runs")
    report = run_certificate(domain, tool_radius, cuts, connectors)
    if len(report.exposed) != len(witnesses):
        raise CertificateRunsDisagreeError(f"{workload}: native run exposes {len(report.exposed)} edges, facade {len(witnesses)} witnesses")
    domain_vertices = len(domain.outer) + sum(len(hole) for hole in domain.holes)
    connector_regions = report.region_count - len(cuts) - domain_vertices
    if connector_regions < 0 or (connectors and connector_regions == 0):
        raise RegionAccountingError(f"{workload}: {report.region_count} regions, {len(cuts)} cuts, {domain_vertices} domain vertices, {len(connectors)} connectors")
    return WorkloadCertificate(
        workload=workload,
        generation_s=generation_s,
        cuts=len(cuts),
        connectors=len(connectors),
        domain_vertices=domain_vertices,
        region_count=report.region_count,
        connector_regions=connector_regions,
        piece_count=report.piece_count,
        edge_count=report.edge_count,
        covered=not witnesses,
        witnesses=len(witnesses),
        undecided=undecided,
        clusters=cluster_witnesses(witnesses),
        runs=tuple(runs),
        median_s=statistics.median(run.seconds for run in runs),
        native_phase_s=report.phase_s,
        repair=repair,
    )


def certify_generated(workload: str) -> WorkloadCertificate:
    """Generate a workload's closed path and certify it."""
    path = generate(workload)
    return certify(workload, path.generation_seconds, path.boundary, path.circles, path.case.tool_radius)


def certify_monstera_repaired() -> WorkloadCertificate:
    """Monstera through select-certify-repair; the repaired path is then certified like every other workload."""
    started = time.perf_counter()
    case = load_held_reference_case("figure8_monstera")
    guide = build_held_reference_raw_guide(case)
    components = figure7_inward_offset(case).components
    if len(components) != 1:
        raise CoverageCertificateAcceptanceError(f"Monstera centre domain has {len(components)} loops, expected 1")
    source = build_held_reference_path(guide, components, qualify_contacts=True)
    cap = EngagementCap.build(math.radians(float(case.tea_cap)))
    certified = refine_boundary_ordered_path_certified(source, components[0], case.tool_radius, cap, corner_approaches=True)
    ledger = certified.ledger
    repair = RepairLedger(
        emitted_before=ledger.emitted_before,
        emitted_after=ledger.emitted_after,
        inserted_sources=tuple(ledger.inserted_sources),
        rounds=ledger.rounds,
        certificate_runs=ledger.certificate_runs,
        repair_s=ledger.repair_s,
        certificate_s=ledger.certificate_s,
    )
    generation_s = time.perf_counter() - started
    return certify(MONSTERA_REPAIRED, generation_s, components[0], certified.emission.refinement.circles, case.tool_radius, repair)


def measure(workloads: Sequence[str] = WORKLOADS) -> AcceptanceRecord:
    """Certify every requested workload, in order.

    Raises:
        CoverageCertificateAcceptanceError: an unknown workload.
    """
    unknown = [name for name in workloads if name not in WORKLOADS]
    if unknown:
        raise CoverageCertificateAcceptanceError(f"unknown workloads {unknown}; known: {list(WORKLOADS)}")
    results = []
    for name in workloads:
        result = certify_monstera_repaired() if name == MONSTERA_REPAIRED else certify_generated(name)
        print(f"{name}: covered={result.covered} witnesses={result.witnesses} clusters={len(result.clusters)} median_s={result.median_s:.3f}", flush=True)
        results.append(result)
    return AcceptanceRecord(GENERATED_BY, SCHEMA, machine_identity(), build_identity(), TIMING_RUNS, CLUSTER_LINK_MM, tuple(results))


def _runs_text(runs: Sequence[TimedRun]) -> str:
    return ", ".join(f"{run.seconds:.2f} @ {run.load_1min:.1f}" for run in runs)


def render_markdown(record: AcceptanceRecord) -> str:
    """The docs table of one acceptance record."""
    build = record.build
    lines = [
        f"<!-- {record.generated_by} -->",
        "",
        f"Coverage certificate on the generated Held paths (closing seam connector included), commit `{build.commit[:12]}`"
        f"{' (dirty tree)' if build.dirty else ''}, {build.recorded_at}, {record.identity.cpu_brand}. "
        f"Time is the facade `CoverageCertificate.build`, median of {record.timing_runs} runs on one core; each run is listed as "
        "`seconds @ 1-min load average` read just before it. Wall clock under the recorded load: it does not transfer between machines or loads. "
        f"Clusters are single linkage at {record.cluster_link_mm:g} mm over the binary64 roundings of the exact witnesses (reporting only).",
        "",
        "| workload | cuts | connectors | connector regions | regions | edges | verdict | witnesses | clusters | median s | runs (s @ load) |",
        "|---|---:|---:|---:|---:|---:|---|---:|---:|---:|---|",
    ]
    for w in record.workloads:
        verdict = "covered" if w.covered else "uncovered"
        lines.append(
            f"| `{w.workload}` | {w.cuts} | {w.connectors} | {w.connector_regions} | {w.region_count} | {w.edge_count} | {verdict} | "
            f"{w.witnesses} | {len(w.clusters)} | {w.median_s:.2f} | {_runs_text(w.runs)} |"
        )
    lines += ["", "Witness clusters:", "", "| workload | centroid (mm) | witnesses | piece kinds |", "|---|---|---:|---|"]
    for w in record.workloads:
        for c in w.clusters:
            lines.append(f"| `{w.workload}` | ({c.centroid_mm[0]:.2f}, {c.centroid_mm[1]:.2f}) | {c.count} | {', '.join(c.kinds)} |")
        if not w.clusters:
            lines.append(f"| `{w.workload}` | none (covered) | 0 | |")
    for w in record.workloads:
        if w.repair is not None:
            r = w.repair
            lines += [
                "",
                f"Repair (`{w.workload}`): {r.emitted_before} -> {r.emitted_after} emitted circles, inserted sources "
                f"{list(r.inserted_sources)}, {r.rounds} round(s), {r.certificate_runs} certificate runs "
                f"({r.certificate_s:.2f} s in total), repair {r.repair_s:.3f} s.",
            ]
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--workloads", nargs="+", default=list(WORKLOADS), choices=WORKLOADS)
    parser.add_argument("--json", type=pathlib.Path, default=JSON_PATH)
    parser.add_argument("--md", type=pathlib.Path, default=MD_PATH)
    args = parser.parse_args(argv)
    record = measure(args.workloads)
    args.json.write_text(record.to_json(), encoding="utf-8")
    args.md.write_text(render_markdown(record), encoding="utf-8")


if __name__ == "__main__":
    main()
