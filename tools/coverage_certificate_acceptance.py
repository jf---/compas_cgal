"""Regenerate the Held toolpaths and record the coverage certificate's verdict, witnesses, regions and time.

Every number the coverage-certificate docs cite for real paths comes from this
tool: the generators (``benchmarks.held_toolpath_benchmark.generate``) build each
path with its closing seam connector, ``benchmarks.held_coverage_repair.path_sweeps``
turns it into the certificate's swept regions, and the certificate runs
through its public facade ``CoverageCertificate.build``. The Monstera path is
also run through select-certify-repair (``refine_boundary_ordered_path_certified``)
and the repaired path is certified the same way.

Times are wall clock on the machine that ran the tool, median of
``TIMING_RUNS`` facade runs, each with the 1-minute load average read just
before it; they do not transfer between machines or loads. Witness clusters are
reporting summaries (``tools.coverage_certificate_clusters``).

Run: ``python -m tools.coverage_certificate_acceptance`` (editable-skip pixi
environment); it rewrites ``benchmarks/results/coverage_certificate_acceptance.{json,md}``.
"""

