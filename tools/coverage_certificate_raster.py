"""Diagnostic raster of the uncut area of the generated Monstera path. REPORTING ONLY, not a certificate.

Pocket: ``case.projection``, the outline the published figure draws. Swept
area: each full-circle cut is the annulus ``| |x - c| - R | <= r``; each
connector is its polyline (+) D_r. A pixel is cut when its centre is in the
swept area, all in binary64. Uncut pixels are grouped into 8-connected
components; a component that touches a pixel outside the pocket is a pocket-tip
crumb (outside T = Omega (+) D_r, see ``docs/held_coverage_certificate.md``),
the others are interior slivers. For each interior sliver the tool lists the
three cuts whose swept band is nearest its centroid (gap = distance to the
band, binary64).

The exact verdict on the same path is ``coverage_certificate_acceptance.md``;
this raster only sizes what the certificate proves uncovered.

Run: ``pixi run coverage-certificate-raster``; it rewrites
``benchmarks/results/coverage_certificate_raster.{json,md}``.
"""

from __future__ import annotations

import argparse
import dataclasses
import json
import pathlib
from collections.abc import Sequence
from dataclasses import dataclass

import numpy as np
from matplotlib.path import Path as MplPath
from scipy import ndimage  # type: ignore[import-untyped]

from benchmarks.performance_record import REPOSITORY
from benchmarks.performance_record import BuildIdentity
from benchmarks.performance_record import MachineIdentity
from benchmarks.performance_record import build_identity
from benchmarks.performance_record import machine_identity
from tools.coverage_certificate_monstera_path import MonsteraPathArrays
from tools.coverage_certificate_monstera_path import load_monstera_path

SCHEMA = "coverage-certificate-raster/1"
JSON_PATH = REPOSITORY / "benchmarks/results/coverage_certificate_raster.json"
MD_PATH = REPOSITORY / "benchmarks/results/coverage_certificate_raster.md"
GENERATED_BY = "Generated by tools/coverage_certificate_raster.py; do not edit, run `pixi run coverage-certificate-raster`."
# Pixel sizes, mm. Two resolutions show the uncut area is resolution-stable; the
# 2026-10-17 diagnostic used the same pair.
PIXEL_MM = (0.02, 0.01)
# Margin around the outline's bounding box, mm: one tool radius, so the outside
# ring that classifies boundary-touching components is never clipped.
GRID_MARGIN_MM = 1.0
# Rows per point-in-polygon batch: bounds the meshgrid memory, no effect on results.
ROW_BATCH = 256
# Components at or above this area (mm^2) are counted as visible slivers;
# reporting threshold of the 2026-10-17 diagnostic.
SLIVER_MM2 = 0.01
LISTED_COMPONENTS = 10
BORDERING_CUTS = 3


@dataclass(frozen=True)
class UncutComponent:
    area_mm2: float
    centroid_mm: tuple[float, float]
    touches_outline: bool
    bordering_cuts: tuple[tuple[int, float], ...]


@dataclass(frozen=True)
class RasterResult:
    pixel_mm: float
    grid: tuple[int, int]
    pocket_mm2: float
    uncut_mm2: float
    components: int
    slivers: int
    interior_uncut_mm2: float
    tip_uncut_mm2: float
    largest: tuple[UncutComponent, ...]


@dataclass(frozen=True)
class RasterRecord:
    generated_by: str
    schema: str
    identity: MachineIdentity
    build: BuildIdentity
    workload: str
    cuts: int
    connectors: int
    tool_radius: float
    results: tuple[RasterResult, ...]

    def to_json(self) -> str:
        return json.dumps(dataclasses.asdict(self), indent=2) + "\n"


def _bordering_cuts(path: MonsteraPathArrays, point: np.ndarray) -> tuple[tuple[int, float], ...]:
    """The ``BORDERING_CUTS`` cuts whose swept band is nearest ``point``: (index, gap mm)."""
    gap = np.abs(np.hypot(*(path.centres - point).T) - path.radii) - path.tool_radius
    nearest = np.argsort(gap)[:BORDERING_CUTS]
    return tuple((int(i), float(gap[i])) for i in nearest)


def rasterise(path: MonsteraPathArrays, px: float) -> RasterResult:
    """Rasterise the swept area at pixel size ``px`` and label the uncut components."""
    r = path.tool_radius
    lo = path.outline.min(axis=0) - GRID_MARGIN_MM
    hi = path.outline.max(axis=0) + GRID_MARGIN_MM
    nx, ny = (int(v) for v in np.ceil((hi - lo) / px))
    xs = lo[0] + (np.arange(nx) + 0.5) * px
    ys = lo[1] + (np.arange(ny) + 0.5) * px
    outline = MplPath(path.outline)
    pocket = np.zeros((ny, nx), dtype=bool)
    for j in range(0, ny, ROW_BATCH):
        gx, gy = np.meshgrid(xs, ys[j : j + ROW_BATCH])
        pocket[j : j + ROW_BATCH] = outline.contains_points(np.column_stack((gx.ravel(), gy.ravel()))).reshape(gx.shape)
    cut = np.zeros_like(pocket)

    def window(box_lo: np.ndarray, box_hi: np.ndarray) -> tuple[slice, slice]:
        i0, j0 = (np.floor((box_lo - lo) / px).astype(int) - 1).clip(0)
        i1, j1 = np.minimum(np.ceil((box_hi - lo) / px).astype(int) + 1, (nx, ny))
        return slice(j0, j1), slice(i0, i1)

    for centre, radius in zip(path.centres, path.radii):
        rows, cols = window(centre - radius - r, centre + radius + r)
        distance = np.hypot(xs[cols][None, :] - centre[0], ys[rows][:, None] - centre[1])
        cut[rows, cols] |= np.abs(distance - radius) <= r
    for polyline in path.connector_samples:
        for a, b in zip(polyline, polyline[1:]) if len(polyline) > 1 else ((polyline[0], polyline[0]),):
            rows, cols = window(np.minimum(a, b) - r, np.maximum(a, b) + r)
            dx, dy = xs[cols][None, :] - a[0], ys[rows][:, None] - a[1]
            v = b - a
            vv = float(v @ v)
            t = np.clip((dx * v[0] + dy * v[1]) / vv, 0.0, 1.0) if vv > 0.0 else 0.0
            cut[rows, cols] |= np.hypot(dx - t * v[0], dy - t * v[1]) <= r
    uncut = pocket & ~cut
    eight = np.ones((3, 3), dtype=bool)
    labels, count = ndimage.label(uncut, structure=eight)
    index = np.arange(1, count + 1)
    area_px = px * px
    sizes = np.asarray(ndimage.sum(uncut, labels, index=index))
    centres = ndimage.center_of_mass(uncut, labels, index=index)
    outside = ndimage.binary_dilation(~pocket, structure=eight)
    touches = np.asarray(ndimage.maximum(outside & uncut, labels, index=index)).astype(bool)
    components = []
    for k in np.argsort(-sizes):
        cy, cx = centres[k]
        centroid = np.array([lo[0] + (cx + 0.5) * px, lo[1] + (cy + 0.5) * px])
        components.append(
            UncutComponent(
                area_mm2=float(sizes[k] * area_px),
                centroid_mm=(float(centroid[0]), float(centroid[1])),
                touches_outline=bool(touches[k]),
                bordering_cuts=() if touches[k] else _bordering_cuts(path, centroid),
            )
        )
    return RasterResult(
        pixel_mm=px,
        grid=(nx, ny),
        pocket_mm2=float(pocket.sum() * area_px),
        uncut_mm2=float(uncut.sum() * area_px),
        components=count,
        slivers=sum(1 for c in components if c.area_mm2 >= SLIVER_MM2),
        interior_uncut_mm2=sum(c.area_mm2 for c in components if not c.touches_outline),
        tip_uncut_mm2=sum(c.area_mm2 for c in components if c.touches_outline),
        largest=tuple(components[:LISTED_COMPONENTS]),
    )


def render_markdown(record: RasterRecord) -> str:
    """The docs tables of one raster record."""
    build = record.build
    lines = [
        f"<!-- {record.generated_by} -->",
        "",
        f"Diagnostic raster (reporting only, not a certificate) of the generated `{record.workload}` path: {record.cuts} cuts, "
        f"{record.connectors} connectors (closing seam included), r = {record.tool_radius:g} mm; commit `{build.commit[:12]}`"
        f"{' (dirty tree)' if build.dirty else ''}, {build.recorded_at}. Pocket = the outline the published figure draws; "
        "a pixel is cut when its centre is in a swept annulus or connector capsule (binary64). "
        f"Slivers are components of at least {SLIVER_MM2:g} mm²; tip crumbs touch the outline.",
        "",
        "| pixel mm | pocket mm² | uncut mm² | fraction | components | slivers ≥ " + f"{SLIVER_MM2:g} mm² | interior uncut mm² | tip-crumb uncut mm² |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for res in record.results:
        lines.append(
            f"| {res.pixel_mm:g} | {res.pocket_mm2:.2f} | {res.uncut_mm2:.4f} | {res.uncut_mm2 / res.pocket_mm2:.2e} | {res.components} | "
            f"{res.slivers} | {res.interior_uncut_mm2:.4f} | {res.tip_uncut_mm2:.4f} |"
        )
    coarse = record.results[0]
    lines += [
        "",
        f"Largest components at {coarse.pixel_mm:g} mm/px (bordering cuts: the {BORDERING_CUTS} cuts whose swept band is nearest the centroid, "
        "`index (gap mm)`, interior components only):",
        "",
        "| # | area mm² | centroid (x, y) mm | touches outline | bordering cuts |",
        "|---:|---:|---|---|---|",
    ]
    for rank, c in enumerate(coarse.largest, start=1):
        bordering = ", ".join(f"{i} ({gap:.3f})" for i, gap in c.bordering_cuts) or "n/a"
        touch = "yes (tip crumb)" if c.touches_outline else "no (interior)"
        lines.append(f"| {rank} | {c.area_mm2:.4f} | ({c.centroid_mm[0]:.2f}, {c.centroid_mm[1]:.2f}) | {touch} | {bordering} |")
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--json", type=pathlib.Path, default=JSON_PATH)
    parser.add_argument("--md", type=pathlib.Path, default=MD_PATH)
    args = parser.parse_args(argv)
    path = load_monstera_path()
    results = tuple(rasterise(path, px) for px in PIXEL_MM)
    record = RasterRecord(GENERATED_BY, SCHEMA, machine_identity(), build_identity(), path.workload, len(path.radii), len(path.connector_samples), path.tool_radius, results)
    args.json.write_text(record.to_json(), encoding="utf-8")
    args.md.write_text(render_markdown(record), encoding="utf-8")


if __name__ == "__main__":
    main()
