SCHEMA = "perf-ratio-history/1"
ENTRY_SCHEMA = "perf-ratio-entry/1"

JSON_PATH = REPOSITORY / "benchmarks" / "results" / "perf_ratio_history.jsonl"
MD_PATH = JSON_PATH.with_suffix(".md")

GENERATED_BY = "<!-- Generated by tools/perf_ratio_history.py from benchmarks/results/perf_ratio_history.jsonl. Do not edit; run `pixi run perf-ratio-render`. -->"
SEMANTICS = "A ratio is a same-moment comparison at any load, never a budget verdict."

# Decimals of a printed ratio: 0.1 % resolution, finer than any run-to-run spread on this machine.
RATIO_DECIMALS = 3
# Characters of a printed commit id in the rendered table (display only; the stage name is `stage_of`'s):
# this repository's ``git log --oneline`` abbreviation, which git sizes from the object count.
SHORT_REV = 8
# Decimals of a printed 1-minute load: the load average's own display precision (``uptime``).
LOAD_DECIMALS = 1

COLUMNS = ("Workload", "Reference", "Machine", "Date", "HEAD", "Ratio", "Pair-ratio median", "Same output", "1-min load")
DIRTY_MARK = "+dirty"


class InjectedRecordError(Exception):
    """The session carries an injected CPU spin (the audit), so its ratios are not measurements."""


class RatioEntryDigestMismatchError(Exception):
    """A history line's stored ``entry_sha256`` is not the digest of its content: the line was edited."""


class MalformedRatioEntryError(Exception):
    """A history line is not a ``perf-ratio-entry/1`` entry: not JSON, wrong schema, keys or field type, or an
    embedded arm or run the session record's builders refuse."""


_TEXT_FIELDS = ("stage", "machine", "cpu_model", "harness_sha256", "recorded_at", "record_sha256")
_CONTENT_KEYS = frozenset(("schema", *_TEXT_FIELDS, "arms", "run"))
_LINE_KEYS = _CONTENT_KEYS | {"entry_sha256"}


@dataclass(frozen=True)
class RatioEntry:
    """One workload's ratio from one honest session, with everything that names what was measured.

    Attributes:
        stage: ``ratio-vs-<ref short rev>`` (`stage_of`): which reference the ratio is against.
        machine: Host name of the machine (the session's ``host``).
        cpu_model: CPU model of the machine.
        harness_sha256: Digest of the harness sources (the session's).
        recorded_at: The session's end, ISO 8601 with a UTC offset.
        record_sha256: SHA-256 of the session record file the entry was read from.
        arms: Both arms' identities: tree, native build and interpreter.
        run: The workload's pairs and both arms' output digests.
    """

    stage: str
    machine: str
    cpu_model: str
    harness_sha256: str
    recorded_at: str
    record_sha256: str
    arms: Mapping[ArmName, ArmIdentity]
    run: WorkloadRatio

    @property
    def workload(self) -> str:
        """The workload's name."""
        return self.run.workload

    @property
    def ref_commit(self) -> str:
        """Full commit id of the reference arm."""
        return self.arms[ArmName.REF].rev

    @property
    def head_rev(self) -> str:
        """Full commit id of the HEAD arm."""
        return self.arms[ArmName.HEAD].rev

    @property
    def head_dirty(self) -> bool:
        """Whether the HEAD arm's tree differed from *head_rev*."""
        return self.arms[ArmName.HEAD].dirty

    @property
    def pairs(self) -> tuple[PairRun, ...]:
        """The interleaved pairs: both arms' CPU and the load around each."""
        return self.run.pairs

    @property
    def ratio(self) -> Ratio:
        """The headline ``min(head) / min(ref)``."""
        return self.run.ratio

    @property
    def pair_ratio_median(self) -> Ratio:
        """The median of per-pair ratios."""
        return self.run.pair_ratio_median

    @property
    def same_output(self) -> bool:
        """Whether both arms produced the same output digest."""
        return self.run.same_output

    @property
    def load_min(self) -> LoadOneMinute:
        """The lowest 1-minute load around any pair."""
        return self.run.load_range[0]

    @property
    def load_max(self) -> LoadOneMinute:
        """The highest 1-minute load around any pair."""
        return self.run.load_range[1]

    @property
    def key(self) -> tuple[str, str, str]:
        """(workload, stage, machine): what one ratio series is."""
        return self.workload, self.stage, self.machine

    @property
    def recorded_instant(self) -> datetime:
        """*recorded_at* parsed.

        Raises:
            MalformedRatioEntryError: *recorded_at* is not ISO 8601 with a UTC offset.
        """
        return _parse_instant(self.recorded_at)

    def _content(self) -> dict[str, object]:
        return {
            "schema": ENTRY_SCHEMA,
            "stage": self.stage,
            "machine": self.machine,
            "cpu_model": self.cpu_model,
            "harness_sha256": self.harness_sha256,
            "recorded_at": self.recorded_at,
            "record_sha256": self.record_sha256,
            "arms": arms_to_json(self.arms),
            "run": self.run.to_json(),
        }

    @property
    def entry_sha256(self) -> str:
        """SHA-256 of the content's canonical JSON (integrity, and the deduplication identity)."""
        return _digest(self._content())

    def to_json_line(self) -> str:
        """The entry as one canonical JSON line with its digest, newline-terminated."""
        document = self._content()
        document["entry_sha256"] = self.entry_sha256
        return _canonical(document) + "\n"

    @classmethod
    def from_json_line(cls, text: str) -> RatioEntry:
        """The entry stored on one history line.

        The stored digest is checked against the line's own content first, so any
        edit is refused as an edit; the embedded arms and run are then checked by
        the session record's builders (`build_arms`, `WorkloadRatio.build`).

        Raises:
            MalformedRatioEntryError: The line is not JSON, not a ``perf-ratio-entry/1`` object with exactly the
                entry keys, a field has the wrong type, *recorded_at* is not ISO 8601 with a UTC offset, *stage* is
                not *ref_commit*'s, an embedded arm or run is refused by its builder, or the content does not
                re-serialise to itself.
            RatioEntryDigestMismatchError: The stored ``entry_sha256`` is not the digest of the line's content.
        """
        try:
            raw = json.loads(text)
        except json.JSONDecodeError as error:
            raise MalformedRatioEntryError(f"a ratio history line is JSON: {error}") from error
        if not isinstance(raw, dict) or raw.get("schema") != ENTRY_SCHEMA:
            raise MalformedRatioEntryError(f"a ratio history line is an object of schema {ENTRY_SCHEMA!r}.")
        if set(raw) != _LINE_KEYS:
            raise MalformedRatioEntryError(f"a ratio history line has exactly the keys {sorted(_LINE_KEYS)}, not {sorted(raw)}.")
        stored = _text(raw, "entry_sha256")
        content = {name: value for name, value in raw.items() if name != "entry_sha256"}
        if _digest(content) != stored:
            raise RatioEntryDigestMismatchError(f"a ratio history line's stored digest {stored} is not its content's {_digest(content)}.")
        try:
            arms = build_arms(raw["arms"], "entry.arms")
            run = WorkloadRatio.build(raw["run"], "entry.run")
        except (MalformedRatioRecordError, InconsistentRatioRecordError, NonPositiveCpuError) as error:
            raise MalformedRatioEntryError(f"a ratio history line embeds a refused part: {error}") from error
        entry = cls(
            stage=_text(raw, "stage"),
            machine=_text(raw, "machine"),
            cpu_model=_text(raw, "cpu_model"),
            harness_sha256=_text(raw, "harness_sha256"),
            recorded_at=_text(raw, "recorded_at"),
            record_sha256=_text(raw, "record_sha256"),
            arms=arms,
            run=run,
        )
        _parse_instant(entry.recorded_at)
        if entry.stage != stage_of(entry.ref_commit):
            raise MalformedRatioEntryError(f"stage {entry.stage!r} is not the reference {entry.ref_commit!r}'s {stage_of(entry.ref_commit)!r}.")
        if entry.entry_sha256 != stored:
            raise MalformedRatioEntryError(f"{entry.workload} / {entry.stage}: the line's content does not re-serialise to itself (a number written in another form).")
        return entry


def entries_of(session: PerfRatioSession, record_sha256: str) -> tuple[RatioEntry, ...]:
    """One entry per workload of an honest *session*, in run order.

    Args:
        session: The checked session.
        record_sha256: SHA-256 of the record file *session* was read from.

    Returns:
        The entries.

    Raises:
        InjectedRecordError: The session carries an injected CPU spin.
    """
    if session.injected is not None:
        raise InjectedRecordError(
            f"the session injected {session.injected.seconds} CPU seconds into the {session.injected.arm.value} arm; an audit record never enters the history."
        )
    arms = {arm: session.arms[arm] for arm in ArmName}
    return tuple(
        RatioEntry(
            stage=session.stage,
            machine=session.host,
            cpu_model=session.cpu_model,
            harness_sha256=session.harness_sha256,
            recorded_at=session.ended_utc,
            record_sha256=record_sha256,
            arms=arms,
            run=workload,
        )
        for workload in session.workloads
    )


def load_record(path: Path = JSON_PATH) -> tuple[RatioEntry, ...]:
    """Every entry of the history at *path*, in file order; empty when the file does not exist.

    Raises:
        UnterminatedHistoryError: The file does not end in a newline.
        DuplicateHistoryEntryError: An ``entry_sha256`` repeats.
        MalformedRatioEntryError: A line is not an entry.
        RatioEntryDigestMismatchError: A line was edited.
    """
    if not path.exists():
        return ()
    text = path.read_text(encoding="utf-8")
    if text and not text.endswith("\n"):
        raise UnterminatedHistoryError(f"{path}: the last line is not newline-terminated.")
    entries = tuple(RatioEntry.from_json_line(line) for line in text.splitlines())
    digests: set[str] = set()
    for entry in entries:
        if entry.entry_sha256 in digests:
            raise DuplicateHistoryEntryError(f"{path}: entry {entry.entry_sha256} ({entry.key}) appears twice.")
        digests.add(entry.entry_sha256)
    return entries


def ingest(record_path: Path, history_path: Path = JSON_PATH) -> tuple[RatioEntry, ...]:
    """Append the entries of the session at *record_path* not yet in the history.

    Returns:
        The entries added, in run order; empty on a re-ingest.

    Raises:
        InjectedRecordError: The session carries an injected CPU spin; the history is untouched.
        AppendOnlyViolationError: The bytes before the append are not a prefix of the bytes after.
        (and everything ``load_session`` and ``load_record`` raise)
    """
    return _ingest_all((record_path,), history_path)


def render_markdown(entries: Sequence[RatioEntry]) -> str:
    """The history as a markdown table: one row per key (keys sorted), its latest entry; the full series stays in the jsonl.

    Raises:
        MalformedRatioEntryError: An entry's *recorded_at* is not ISO 8601 with a UTC offset.
    """
    latest: dict[tuple[str, str, str], RatioEntry] = {}
    for entry in entries:
        # Ties on the instant break on the digest, so the row does not depend on the input order.
        current = latest.get(entry.key)
        if current is None or (entry.recorded_instant, entry.entry_sha256) > (current.recorded_instant, current.entry_sha256):
            latest[entry.key] = entry
    lines = [GENERATED_BY, "", SEMANTICS, "", _row(COLUMNS), _row(tuple("---" for _ in COLUMNS))]
    lines.extend(_row(_cells(latest[key])) for key in sorted(latest))
    return "\n".join(lines) + "\n"


def write_markdown(history_path: Path = JSON_PATH, markdown_path: Path = MD_PATH) -> str:
    """Render the history at *history_path* to *markdown_path*.

    Returns:
        The markdown written.
    """
    markdown = render_markdown(load_record(history_path))
    markdown_path.write_text(markdown, encoding="utf-8")
    return markdown


def main(argv: Optional[Sequence[str]] = None) -> int:
    """``ingest RECORD...`` (every record is checked before any is appended) or ``render``.

    Returns:
        The exit status.
    """
    parser = argparse.ArgumentParser(prog="python -m tools.perf_ratio_history", description="Ingest perf-ratio/1 records into the ratio history, or render it.")
    commands = parser.add_subparsers(dest="command", required=True)
    ingest_parser = commands.add_parser("ingest", help="append perf-ratio/1 records' entries; refuses injected records")
    ingest_parser.add_argument("records", nargs="+", type=Path, metavar="RECORD")
    commands.add_parser("render", help=f"regenerate {MD_PATH.relative_to(REPOSITORY)}")
    arguments = parser.parse_args(argv)
    if arguments.command == "ingest":
        added = _ingest_all(tuple(arguments.records), JSON_PATH)
        print(f"appended {len(added)} entries")
    else:
        write_markdown(JSON_PATH, MD_PATH)
    return 0


def _ingest_all(record_paths: Sequence[Path], history_path: Path) -> tuple[RatioEntry, ...]:
    # Every record is read and checked before the history is touched, so a refused record appends nothing.
    candidates = [entry for record_path in record_paths for entry in entries_of(load_session(record_path), sha256_file(record_path))]
    present = {entry.entry_sha256 for entry in load_record(history_path)}
    added: list[RatioEntry] = []
    for entry in candidates:
        if entry.entry_sha256 in present:
            continue
        present.add(entry.entry_sha256)
        added.append(entry)
    _append_text(history_path, "".join(entry.to_json_line() for entry in added))
    return tuple(added)


def _append_text(path: Path, text: str) -> None:
    before = path.read_bytes() if path.exists() else b""
    if text:
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("a", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
    after = path.read_bytes() if path.exists() else b""
    if not after.startswith(before):
        raise AppendOnlyViolationError(f"{path}: the existing {len(before)} bytes changed during the append.")


def _canonical(document: Mapping[str, object]) -> str:
    return json.dumps(document, sort_keys=True, separators=(",", ":"))


def _digest(content: Mapping[str, object]) -> str:
    return hashlib.sha256(_canonical(content).encode("utf-8")).hexdigest()


def _parse_instant(value: str) -> datetime:
    try:
        parsed = datetime.fromisoformat(value)
    except ValueError as error:
        raise MalformedRatioEntryError(f"recorded_at {value!r} is not ISO 8601.") from error
    if parsed.utcoffset() is None:
        raise MalformedRatioEntryError(f"recorded_at {value!r} carries no UTC offset.")
    return parsed


def _text(raw: Mapping[str, Any], name: str) -> str:
    value = raw[name]
    if not isinstance(value, str):
        raise MalformedRatioEntryError(f"{name} is a string, not {value!r}.")
    return value


def _row(cells: Sequence[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def _cells(entry: RatioEntry) -> tuple[str, ...]:
    return (
        entry.workload,
        f"`{entry.ref_commit[:SHORT_REV]}`",
        entry.machine,
        entry.recorded_instant.astimezone(timezone.utc).date().isoformat(),
        f"`{entry.head_rev[:SHORT_REV]}`" + (DIRTY_MARK if entry.head_dirty else ""),
        _ratio(entry.ratio),
        _ratio(entry.pair_ratio_median),
        "yes" if entry.same_output else "no",
        f"{entry.load_min:.{LOAD_DECIMALS}f}–{entry.load_max:.{LOAD_DECIMALS}f}",
    )


def _ratio(value: Ratio) -> str:
    return f"{value:.{RATIO_DECIMALS}f}×"


if __name__ == "__main__":
    raise SystemExit(main())
