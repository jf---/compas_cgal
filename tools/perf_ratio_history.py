"""The ratio history: ``benchmarks/results/perf_ratio_history.jsonl`` and its rendered table.

Each line is one ``perf-ratio-entry/1`` entry: one workload of one honest
``perf-ratio/1`` session, keyed by ``(workload, ratio-vs-<ref short rev>, machine)``.
An entry is self-contained: it embeds both arms' identities (tree, native build
and interpreter), the workload's every pair (both arms' CPU, the load around
it), the harness digest and the CPU model, so it still names what was measured
after the session record it came from is overwritten. The embedded parts are
checked by the session record's own builders on every load.
The history is separate from ``perf_history.jsonl``: a ratio is dimensionless,
has no baseline and no check, and is valid at any load.

Lines are only ever appended. ``ingest`` writes in append mode and then re-reads
the file to verify the bytes that were there before are unchanged
(``AppendOnlyViolationError`` otherwise). An entry whose ``entry_sha256`` is
already present is not written again, so re-ingesting a record is a no-op.
Loading re-derives every line's digest (an edited line is refused) and refuses a
repeated digest. A session that carries an injected CPU spin (the audit) is
refused before the history is touched.
"""

