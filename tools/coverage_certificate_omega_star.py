@dataclass(frozen=True)
class _PieceDistance:
    """Exact distance ``|√a + k|`` (rational ``a >= 0``, ``k``) from a rational point to one declared primitive.

    Attributes:
        a: Rational radicand (``0`` for a line foot).
        k: Rational shift (``0`` for a distance to a point, ``-ρ`` for an arc interior).
        at_junction: Whether the primitive's nearest point is one of its ends (decided exactly).
    """

    a: Fraction
    k: Fraction
    at_junction: bool

    def squared(self) -> OneRootNumber:
        """``(√a + k)² = a + k² + 2k√a`` exactly."""
        return OneRootNumber.build(self.a + self.k * self.k, 2 * self.k, self.a)

    def report_mm(self) -> float:
        """``|√a + k|`` in millimetres via a high-precision decimal (reporting only, never a decision)."""
        with decimal.localcontext() as context:
            context.prec = REPORT_DECIMAL_DIGITS
            root = (decimal.Decimal(self.a.numerator) / decimal.Decimal(self.a.denominator)).sqrt()
            return float(abs(root + decimal.Decimal(self.k.numerator) / decimal.Decimal(self.k.denominator)))


def _squared(point: ExactXY, other: ExactPoint2[WorldXY]) -> Fraction:
    dx, dy = point[0] - other.x, point[1] - other.y
    return dx * dx + dy * dy


def _end_distance(point: ExactXY, primitive: DeclaredPrimitive) -> _PieceDistance:
    return _PieceDistance(min(_squared(point, primitive.start), _squared(point, primitive.end)), Fraction(0), True)


def _line_distance(point: ExactXY, line: DeclaredLine) -> _PieceDistance:
    ux, uy = line.direction.vector  # exactly unit (Pythagorean)
    dx, dy = point[0] - line.start.x, point[1] - line.start.y
    along = ux * dx + uy * dy
    if 0 <= along <= line.length:
        return _PieceDistance(Fraction(0), ux * dy - uy * dx, along == 0 or along == line.length)
    return _end_distance(point, line)


def _arc_distance(point: ExactXY, arc: DeclaredArc) -> _PieceDistance:
    centre = arc.centre
    dx, dy = point[0] - centre.x, point[1] - centre.y
    square = dx * dx + dy * dy
    if square == 0:
        return _PieceDistance(Fraction(0), arc.radius, False)
    start, probe = OneRootPoint2.from_exact(arc.start), OneRootPoint2.rational(*point)
    order = compare_on_arc(centre, arc.sense, start, probe, OneRootPoint2.from_exact(arc.end))
    if order <= 0:
        on_end = order == 0 or compare_on_arc(centre, arc.sense, start, start, probe) == 0
        return _PieceDistance(square, -arc.radius, on_end)
    return _end_distance(point, arc)


def _piece_distance(point: ExactXY, primitive: DeclaredPrimitive) -> _PieceDistance:
    if isinstance(primitive, DeclaredLine):
        return _line_distance(point, primitive)
    return _arc_distance(point, primitive)


@dataclass(frozen=True)
class WitnessAttribution:
    """The declared piece realising a witness's exact minimum distance to the declared boundary.

    Attributes:
        primitive_index: Index of the piece in the boundary (ties: the lowest index).
        feature: ``line``, ``convex arc``, ``concave arc``, or ``junction`` when the
            piece's nearest point is one of its ends.
        radius_mm: Radius of an arc piece, 0 for a line (reporting).
        squared_depth: Exact squared distance to the declared boundary.
        depth_mm: That distance in millimetres (reporting only).
    """

    primitive_index: int
    feature: str
    radius_mm: float
    squared_depth: OneRootNumber
    depth_mm: float


@dataclass(frozen=True)
class _PieceBox:
    """A rational superset box of one primitive and an anchor point on it (exact pruning)."""

    low: ExactXY
    high: ExactXY
    anchor: ExactXY


def _piece_box(primitive: DeclaredPrimitive) -> _PieceBox:
    anchor = (Fraction(primitive.start.x), Fraction(primitive.start.y))
    if isinstance(primitive, DeclaredLine):
        end = primitive.end
        low = (min(anchor[0], Fraction(end.x)), min(anchor[1], Fraction(end.y)))
        high = (max(anchor[0], Fraction(end.x)), max(anchor[1], Fraction(end.y)))
        return _PieceBox(low, high, anchor)
    # The full circle's box contains the arc.
    centre, radius = primitive.centre, primitive.radius
    return _PieceBox((centre.x - radius, centre.y - radius), (centre.x + radius, centre.y + radius), anchor)


def _gap(low: Fraction, high: Fraction, other_low: Fraction, other_high: Fraction) -> Fraction:
    return max(Fraction(0), other_low - high, low - other_high)


@dataclass(frozen=True)
class WitnessAttributor:
    """Exact nearest-piece attribution against one declared boundary.

    Every distance is a closed form ``|√a + k|`` over the declared rationals and
    the witness's exact coordinates; the minimum is taken with exact one-root
    comparisons, ties going to the lowest primitive index. Pruning is exact: a
    piece is skipped only when the squared distance between its rational box
    and the query box exceeds the squared distance from the query box's
    farthest corner to a point on some piece (rational comparisons).
    """

    primitives: tuple[DeclaredPrimitive, ...]
    boxes: tuple[_PieceBox, ...]

    @classmethod
    def build(cls, primitives: Sequence[DeclaredPrimitive]) -> WitnessAttributor:
        """Precompute the pruning boxes."""
        return cls(tuple(primitives), tuple(_piece_box(p) for p in primitives))

    def candidates(self, low: ExactXY, high: ExactXY, within: Sequence[int] | None = None) -> list[int]:
        """Ascending indices of the pieces that can be nearest to some point of the box ``[low, high]``."""
        indices = range(len(self.primitives)) if within is None else within

        def farthest(box: _PieceBox) -> Fraction:
            ax, ay = box.anchor
            return max((low[0] - ax) ** 2, (high[0] - ax) ** 2) + max((low[1] - ay) ** 2, (high[1] - ay) ** 2)

        def nearest(box: _PieceBox) -> Fraction:
            return _gap(low[0], high[0], box.low[0], box.high[0]) ** 2 + _gap(low[1], high[1], box.low[1], box.high[1]) ** 2

        bound = min(farthest(self.boxes[i]) for i in indices)
        return sorted(i for i in indices if nearest(self.boxes[i]) <= bound)

    def attribute(self, point: ExactXY, within: Sequence[int] | None = None) -> WitnessAttribution:
        """The piece realising the exact minimum distance from ``point``.

        Args:
            point: Exact witness coordinates.
            within: Candidate indices that contain every possible nearest piece
                (from :meth:`candidates` on a box containing ``point``); all pieces when ``None``.
        """
        best_index, best, best_squared = -1, _PieceDistance(Fraction(0), Fraction(0), False), OneRootNumber.of(0)
        for index in self.candidates(point, point, within):
            distance = _piece_distance(point, self.primitives[index])
            squared = distance.squared()
            if best_index < 0 or squared.compare(best_squared) < 0:
                best_index, best, best_squared = index, distance, squared
        primitive = self.primitives[best_index]
        if best.at_junction:
            feature = "junction"
        elif isinstance(primitive, DeclaredLine):
            feature = "line"
        else:
            feature = "convex arc" if primitive.sense == 1 else "concave arc"
        radius = 0.0 if isinstance(primitive, DeclaredLine) else float(primitive.radius)
        return WitnessAttribution(best_index, feature, radius, best_squared, best.report_mm())


def attribute_witness(point: ExactXY, primitives: Sequence[DeclaredPrimitive]) -> WitnessAttribution:
    """The declared piece realising the exact minimum distance from ``point`` (ties: lowest index)."""
    return WitnessAttributor.build(primitives).attribute(point)


def _capsules(domain: CentreDomain, connectors: Sequence[BoundaryConnectorSweep]) -> list[Capsule]:
    """The straight pieces of every connector, exact (Fractions of the injected loop vertices)."""
    loop = [(Fraction(float(p.x)), Fraction(float(p.y))) for p in domain.outer]
    n = len(loop)

    def site(segment: int, t: Fraction) -> tuple[Fraction, Fraction]:
        a, b = loop[segment], loop[(segment + 1) % n]
        return a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1])

    pieces = []
    for c in connectors:
        points = [site(c.start.segment, c.start.parameter)]
        segment = c.start.segment
        if not (c.start.segment == c.end.segment and c.start.parameter < c.end.parameter):
            segment = (segment + 1) % n
            points.append(loop[segment])
            while segment != c.end.segment:
                segment = (segment + 1) % n
                points.append(loop[segment])
        points.append(site(c.end.segment, c.end.parameter))
        pieces += [(points[i], points[i + 1]) for i in range(len(points) - 1) if points[i] != points[i + 1]]
    return pieces


