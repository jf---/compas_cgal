def _cluster_members(witnesses: Sequence[UncoveredWitness], clusters: Sequence[WitnessCluster]) -> list[list[int]]:
    """Member indices of each shared reporting cluster, in the clusters' order.

    The same single linkage as ``cluster_witnesses`` (``math.dist < CLUSTER_LINK_MM``
    on the reported points), with grid buckets of the link size so only
    neighbouring buckets are compared (pairs in non-adjacent buckets are farther
    apart than the link). Reporting only.

    Raises:
        ClusterMembershipMismatchError: The grouping disagrees with ``clusters``.
    """
    points = [tuple(map(float, w.uncovered_point_mm)) for w in witnesses]
    parent = list(range(len(points)))

    def root(i: int) -> int:
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    buckets: dict[tuple[int, int], list[int]] = {}
    for i, (x, y) in enumerate(points):
        key = (math.floor(x / CLUSTER_LINK_MM), math.floor(y / CLUSTER_LINK_MM))
        for bx in (key[0] - 1, key[0], key[0] + 1):
            for by in (key[1] - 1, key[1], key[1] + 1):
                for j in buckets.get((bx, by), ()):
                    if math.dist(points[i], points[j]) < CLUSTER_LINK_MM:
                        parent[root(i)] = root(j)
        buckets.setdefault(key, []).append(i)
    groups: dict[int, list[int]] = {}
    for i in range(len(points)):
        groups.setdefault(root(i), []).append(i)
    by_summary = {
        (statistics.fmean(points[i][0] for i in m), statistics.fmean(points[i][1] for i in m), len(m), tuple(sorted({witnesses[i].piece_kind.name for i in m}))): m
        for m in groups.values()
    }
    members = []
    for cluster in clusters:
        summary = (cluster.centroid_mm[0], cluster.centroid_mm[1], cluster.count, cluster.kinds)
        if summary not in by_summary:
            raise ClusterMembershipMismatchError(f"cluster at {cluster.centroid_mm} ({cluster.count} witnesses) has no matching member group")
        members.append(by_summary.pop(summary))
    if by_summary:
        raise ClusterMembershipMismatchError(f"{len(by_summary)} member groups match no shared cluster")
    return members


def _decimal(value: OneRootNumber) -> decimal.Decimal:
    def rational(q: Fraction) -> decimal.Decimal:
        return decimal.Decimal(q.numerator) / decimal.Decimal(q.denominator)

    return rational(value.rational) + rational(value.coefficient) * rational(value.radicand).sqrt()


def _target_depth_mm(omega: ExactCentreDomain, point: ExactXY, r: Fraction) -> float:
    """``r - dist(p, Omega*)`` from the exact squared distance, printed via decimals (reporting only)."""
    squared = omega.squared_distance_to(ExactPoint2[WorldXY].build(*point))
    with decimal.localcontext() as context:
        context.prec = REPORT_DECIMAL_DIGITS
        return float(decimal.Decimal(r.numerator) / decimal.Decimal(r.denominator) - max(_decimal(squared), decimal.Decimal(0)).sqrt())


def _cluster_record(
    cluster: WitnessCluster, members: Sequence[int], exact_points: Sequence[ExactXY], attributor: WitnessAttributor, omega: ExactCentreDomain, r: Fraction
) -> ClusterRecord:
    """Attribute every member exactly and classify the cluster (attribution exact, depths reporting)."""
    xs, ys = [exact_points[i][0] for i in members], [exact_points[i][1] for i in members]
    within = attributor.candidates((min(xs), min(ys)), (max(xs), max(ys)))
    attributions = [attributor.attribute(exact_points[i], within) for i in members]
    deepest = attributions[0]
    for attribution in attributions[1:]:
        if attribution.squared_depth.compare(deepest.squared_depth) > 0:
            deepest = attribution
    named = next((name for name, xy in NAMED_SLIVERS.items() if math.dist(cluster.centroid_mm, xy) < NAMED_SLIVER_RADIUS_MM), None)
    if named is not None:
        cluster_class = f"interior {named}"
    elif deepest.squared_depth.compare(HAIRLINE_DEPTH_MM * HAIRLINE_DEPTH_MM) <= 0:
        cluster_class = "hairline"
    elif deepest.feature == "convex arc":
        cluster_class = "chord sliver"
    else:
        cluster_class = "unexplained"
    return ClusterRecord(
        centroid_mm=cluster.centroid_mm,
        count=cluster.count,
        kinds=cluster.kinds,
        label=named if named is not None else deepest.feature,
        cluster_class=cluster_class,
        witnesses_by_feature=tuple(sum(1 for a in attributions if a.feature == f) for f in FEATURES),
        deepest_feature=deepest.feature,
        deepest_primitive=deepest.primitive_index,
        feature_radius_mm=deepest.radius_mm,
        depth_mm=deepest.depth_mm,
        target_depth_mm=max(_target_depth_mm(omega, exact_points[i], r) for i in members),
    )


def measure(*, indicative: bool = False) -> OmegaStarRecord:
    """Measure the production budget gate, then the diagnostic: certify TIMING_RUNS times, re-check and attribute.

    The gate runs first, so a loaded machine fails (gated) before the diagnostic's minutes of work.

    Raises:
        MachineNotQuietError: gated, and the machine is not quiet.
        OmegaStarCertificateError: an independent re-check disagrees with a witness.
    """
    budget = measure_budget_runs(indicative=indicative)
    path = generate(MONSTERA)
    tool = path.case.tool_radius
    r = Fraction(float(tool.value))
    case = load_held_reference_case(CASE)
    started = time.perf_counter()
    declared = declared_boundary_from_reference(CASE, case.boundary)
    omega = ExactCentreDomain.build(declared, r)
    target = exact_coverage_target(declared, omega)
    target_build_s = time.perf_counter() - started
    domain = CentreDomain.build(list(path.boundary))
    cuts, connectors = path_sweeps(domain, path.boundary, path.circles)
    walls, cpus, loads = [], [], []
    report: CertificateReport | None = None
    for _ in range(TIMING_RUNS):
        loads.append(os.getloadavg()[0])
        wall, cpu = time.perf_counter(), time.process_time()
        report = run_certificate(domain, tool, cuts, connectors, exact_target=target)
        walls.append(time.perf_counter() - wall)
        cpus.append(time.process_time() - cpu)
    if report is None:
        raise OmegaStarCertificateError("no certificate run (TIMING_RUNS must be positive)")
    polygon_walls = []
    polygon = None
    for _ in range(TIMING_RUNS):
        wall = time.perf_counter()
        polygon = run_certificate(domain, tool, cuts, connectors)
        polygon_walls.append(time.perf_counter() - wall)
    if polygon is None:
        raise OmegaStarCertificateError("no polygonal certificate run")
    witnesses = [UncoveredWitness(e.piece_kind, e.region_index, e.uncovered) for e in report.exposed]
    oracle = SweptOracle.build(r, _annuli(cuts), _capsules(domain, connectors))
    points = [w.uncovered_point_mm for w in witnesses]
    exact_points = [(Fraction(w.uncovered_point[0]), Fraction(w.uncovered_point[1])) for w in witnesses]
    shared = cluster_witnesses(witnesses)
    started = time.perf_counter()
    attributor = WitnessAttributor.build(declared.primitives)
    clusters = []
    for cluster, members in zip(shared, _cluster_members(witnesses, shared)):
        first = min(range(len(points)), key=lambda i: math.dist(points[i], cluster.centroid_mm))
        exact = exact_points[first]
        if omega.squared_distance_to(ExactPoint2[WorldXY].build(*exact)).compare(r * r) > 0:
            raise OmegaStarCertificateError(f"witness {exact} is not in T by the Omega* distance oracle")
        if oracle.covers(exact):
            raise OmegaStarCertificateError(f"witness {exact} is swept by the Fraction oracle")
        clusters.append(_cluster_record(cluster, members, exact_points, attributor, omega, r))
    attribution_s = time.perf_counter() - started
    return OmegaStarRecord(
        generated_by=GENERATED_BY,
        schema=SCHEMA,
        identity=machine_identity(),
        build=build_identity(),
        budget=budget,
        cuts=len(cuts),
        connectors=len(connectors),
        target_pieces=len(target.pieces),
        vertex_disks=len(target.vertex_disks),
        one_root_vertex_disks=sum(1 for d in target.vertex_disks if d.radicand != 0),
        target_build_s=target_build_s,
        attribution_s=attribution_s,
        region_count=report.region_count,
        piece_count=report.piece_count,
        edge_count=report.edge_count,
        witnesses=len(report.exposed),
        undecided=report.undecided,
        runs_wall_s=tuple(walls),
        runs_cpu_s=tuple(cpus),
        runs_load=tuple(loads),
        median_wall_s=statistics.median(walls),
        median_cpu_s=statistics.median(cpus),
        native_phase_s=report.phase_s,
        polygon_target_median_wall_s=statistics.median(polygon_walls),
        polygon_target_witnesses=len(polygon.exposed),
        counters=dict(report.counters),
        clusters=tuple(clusters),
    )


def render_markdown(record: OmegaStarRecord) -> str:
    """The docs tables of one record: the budget gate first, then the diagnostic (no verdict)."""
    b = record.build
    by_class: dict[str, tuple[int, int, float]] = {}
    for c in record.clusters:
        n, w, hi = by_class.get(c.cluster_class, (0, 0, 0.0))
        by_class[c.cluster_class] = (n + 1, w + c.count, max(hi, c.depth_mm))
    totals = [sum(c.witnesses_by_feature[k] for c in record.clusters) for k in range(len(FEATURES))]
    lines = [
        f"<!-- {record.generated_by} -->",
        "",
        f"Recorded at commit `{b.commit[:12]}`{' (dirty tree)' if b.dirty else ''}, {b.recorded_at}, {record.identity.cpu_brand}.",
        "",
        *render_budget(record.budget),
        "",
        f"**Diagnostic, not the budget gate.** Monstera path (current generator, polygonal centre domain) certified against T(Omega*) "
        f"to prove and attribute its non-coverage; its time includes producing every witness and is never compared with the budget. "
        f"{record.cuts} cuts, {record.connectors} connectors; target {record.target_pieces} dOmega* pieces, "
        f"{record.vertex_disks} vertex disks ({record.one_root_vertex_disks} one-root), built in {record.target_build_s:.2f} s.",
        "",
        "| target (diagnostic) | witnesses | clusters | median wall s | CPU s min / median | runs CPU s @ load | phases wall s (crossings, circles, flanks, witnesses) |",
        "|---|---:|---:|---:|---:|---|---|",
        f"| T(Omega*) | {record.witnesses} | {len(record.clusters)} | {record.median_wall_s:.2f} | "
        f"{min(record.runs_cpu_s):.2f} / {record.median_cpu_s:.2f} | {', '.join(f'{c:.2f} @ {lo:.0f}' for c, lo in zip(record.runs_cpu_s, record.runs_load))} | "
        f"{', '.join(f'{x:.2f}' for x in record.native_phase_s)} |",
        f"| T(Omega) polygonal (same path) | {record.polygon_target_witnesses} | | {record.polygon_target_median_wall_s:.2f} | | | |",
        "",
        "Every witness is attributed to the declared piece realising its exact minimum distance (exact one-root comparisons, "
        "ties to the lowest primitive index; `junction` when that piece's nearest point is one of its ends). "
        f"Clusters by class (hairline: every member within {float(HAIRLINE_DEPTH_MM):g} mm of the declared boundary, decided exactly; "
        "chord sliver: deepest member on a convex arc; A and B are the known interior slivers):",
        "",
        "| class | clusters | witnesses | max depth from the declared boundary, mm |",
        "|---|---:|---:|---:|",
    ]
    lines += [f"| {name} | {n} | {w} | {hi:.1e} |" for name, (n, w, hi) in sorted(by_class.items(), key=lambda kv: -kv[1][1])]
    lines += [
        "",
        f"Witnesses by attributed feature ({record.attribution_s:.1f} s for all {record.witnesses}): " + ", ".join(f"{name} {n}" for name, n in zip(FEATURES, totals)) + ".",
        "",
        "Every cluster (depth: the deepest member's distance from the declared boundary, an upper bound on its distance to dT; "
        "r - dist(p, Omega*): the largest over the members, a lower bound on the distance to dT):",
        "",
        "| centroid (mm) | witnesses | line / convex / concave / junction | kinds | class | deepest piece | arc radius mm | depth mm | r - dist(p, Omega*) mm |",
        "|---|---:|---|---|---|---|---:|---:|---:|",
    ]
    for c in record.clusters:
        lines.append(
            f"| ({c.centroid_mm[0]:.3f}, {c.centroid_mm[1]:.3f}) | {c.count} | {' / '.join(map(str, c.witnesses_by_feature))} | {', '.join(c.kinds)} | "
            f"{c.cluster_class} | {c.deepest_feature} {c.deepest_primitive} | {c.feature_radius_mm:.3f} | {c.depth_mm:.1e} | {c.target_depth_mm:.1e} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--json", type=pathlib.Path, default=JSON_PATH)
    parser.add_argument("--md", type=pathlib.Path, default=MD_PATH)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--render", action="store_true", help="re-render the Markdown from the JSON without measuring (refuses another schema)")
    mode.add_argument("--indicative", action="store_true", help="measure at any load; the budget runs are recorded as indicative, with no verdict")
    args = parser.parse_args(argv)
    if args.render:
        record = load_record(args.json)
    else:
        record = measure(indicative=args.indicative)
        args.json.write_text(record.to_json(), encoding="utf-8")
    args.md.write_text(render_markdown(record), encoding="utf-8")
    budget = record.budget
    print(f"budget {budget.workload}: {budget.verdict.value}, CPU min {budget.cpu.minimum:.2f} s; diagnostic: {record.witnesses} witnesses, {len(record.clusters)} clusters")


if __name__ == "__main__":
    main()
