def _floats(values: Sequence[float]) -> tuple[float, ...]:
    return tuple(float(v) for v in values)


def load_record(path: pathlib.Path) -> OmegaStarRecord:
    """Read a record written by :meth:`OmegaStarRecord.to_json`, re-validating the budget.

    Raises:
        StaleOmegaStarRecordError: the record's schema is not ``SCHEMA``.
        BudgetRunCountError: the budget does not hold ``BUDGET_RUNS`` runs (``tools.coverage_certificate_budget_gate``).
        MachineNotQuietError: a gated budget run was measured under load.
    """
    raw: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    if raw.get("schema") != SCHEMA:
        raise StaleOmegaStarRecordError(
            f"{path}: schema {raw.get('schema')!r}, expected {SCHEMA!r}; re-measure on a quiet machine (`pixi run coverage-certificate-omega-star`), never render it"
        )
    phases = _floats(raw["native_phase_s"])
    clusters = tuple(
        ClusterRecord(
            **{**c, "centroid_mm": (float(c["centroid_mm"][0]), float(c["centroid_mm"][1])), "kinds": tuple(c["kinds"]), "witnesses_by_feature": tuple(c["witnesses_by_feature"])}
        )
        for c in raw["clusters"]
    )
    return OmegaStarRecord(
        **{
            **raw,
            "identity": MachineIdentity(**raw["identity"]),
            "build": BuildIdentity(**raw["build"]),
            "budget": ProductionBudget.from_raw(raw["budget"]),
            "runs_wall_s": _floats(raw["runs_wall_s"]),
            "runs_cpu_s": _floats(raw["runs_cpu_s"]),
            "runs_load": _floats(raw["runs_load"]),
            "native_phase_s": (phases[0], phases[1], phases[2], phases[3]),
            "clusters": clusters,
        }
    )


