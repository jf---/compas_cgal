@dataclass(frozen=True)
class SweptOracle:
    """Exact closed membership in the union U of cut annuli and connector capsules, behind an exact grid index.

    Each sweep is registered in every integer (1 mm) cell its rational bounding
    box meets: centre ± (R + r) for an annulus, the endpoint box ± r for a
    capsule. The box contains the sweep and ``math.floor`` on a Fraction is
    exact, so the cell of a point lists every sweep that can contain it (a
    provable superset). Membership is Fraction arithmetic; no binary64 value
    decides which sweeps are tested.

    Attributes:
        tool: Tool radius r.
        annuli: ``(cx, cy, R)`` of each cut: closed band ``max(R - r, 0) <= |p - c| <= R + r``.
        capsules: Segment ends of each connector piece: closed ``dist(p, [a, b]) <= r``.
        cells: Cell ``(floor x, floor y)`` -> sweep indices (annuli first, then capsules).
    """

    tool: Fraction
    annuli: tuple[Annulus, ...]
    capsules: tuple[Capsule, ...]
    cells: dict[tuple[int, int], tuple[int, ...]]

    @classmethod
    def build(cls, tool: Fraction, annuli: Sequence[Annulus], capsules: Sequence[Capsule]) -> SweptOracle:
        """Index the sweeps by the integer cells of their rational bounding boxes."""
        cells: dict[tuple[int, int], list[int]] = {}

        def register(index: int, low: ExactXY, high: ExactXY) -> None:
            for x in range(math.floor(low[0]), math.floor(high[0]) + 1):
                for y in range(math.floor(low[1]), math.floor(high[1]) + 1):
                    cells.setdefault((x, y), []).append(index)

        for index, (cx, cy, big_r) in enumerate(annuli):
            reach = big_r + tool
            register(index, (cx - reach, cy - reach), (cx + reach, cy + reach))
        for offset, (a, b) in enumerate(capsules):
            low, high = (min(a[0], b[0]) - tool, min(a[1], b[1]) - tool), (max(a[0], b[0]) + tool, max(a[1], b[1]) + tool)
            register(len(annuli) + offset, low, high)
        return cls(tool, tuple(annuli), tuple(capsules), {cell: tuple(indices) for cell, indices in cells.items()})

    def _member(self, index: int, point: ExactXY) -> bool:
        if index < len(self.annuli):
            cx, cy, big_r = self.annuli[index]
            d2 = (point[0] - cx) ** 2 + (point[1] - cy) ** 2
            return max(big_r - self.tool, Fraction(0)) ** 2 <= d2 <= (big_r + self.tool) ** 2
        a, b = self.capsules[index - len(self.annuli)]
        dx, dy = b[0] - a[0], b[1] - a[1]
        t = min(max(((point[0] - a[0]) * dx + (point[1] - a[1]) * dy) / (dx * dx + dy * dy), Fraction(0)), Fraction(1))
        return (point[0] - a[0] - t * dx) ** 2 + (point[1] - a[1] - t * dy) ** 2 <= self.tool * self.tool

    def covers(self, point: ExactXY) -> bool:
        """Whether ``point`` lies in U (exact, closed), testing only the sweeps registered in its cell."""
        return any(self._member(i, point) for i in self.cells.get((math.floor(point[0]), math.floor(point[1])), ()))

    def member_of_any(self, point: ExactXY) -> bool:
        """The same decision by scanning every sweep (the index-free reference)."""
        return any(self._member(i, point) for i in range(len(self.annuli) + len(self.capsules)))


def _annuli(cuts: Sequence[FullCircleSweep]) -> list[Annulus]:
    """Each cut's exact centre and path radius (exact injection of the binary64 values)."""
