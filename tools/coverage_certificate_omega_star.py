"""Diagnose the polygonal Monstera path against T(Omega*), and record the production budget gate beside it.

The record holds two workloads, kept apart:

- Budget gate (``budget``): measured by ``tools.coverage_certificate_budget_gate``
  on the production workload (the Omega*-built Monstera path), process CPU,
  minimum of 5 fresh runs, quiet machine only; ``--indicative`` records the
  runs at any load with no verdict.
- Diagnostic (every other field, never gated): the path below, certified
  against T(Omega*) to prove and attribute its non-coverage.

The diagnostic path is the current generator's (``benchmarks.held_toolpath_benchmark.generate``):
binary64 full circles plus connectors along the polygonal centre domain Omega.
The target is T = Omega* (+) D_r of the declared (Pythagorean) boundary
(``benchmarks.held_exact_centre_domain``), cut into the certificate exactly
(``CoverageCertificate.build(..., exact_target=...)``). The path is not built on
Omega*, so the certificate is expected to prove non-coverage; this tool reports
every witness cluster and attributes it.

Every cluster's first witness is re-checked independently of the certificate:
in T by the exact squared distance to Omega* (``CentreDomain.squared_distance_to``,
the native centre-domain module), and outside every sweep by Fraction arithmetic
against every cut annulus and connector capsule whose rational bounding box
meets the witness's integer cell (``SweptOracle``, an exact superset index).

Every witness is attributed to the declared piece realising its exact minimum
distance to the declared boundary (closed forms ``|√a + k|`` compared as
one-root numbers, ties to the lowest primitive index), and a cluster is a
hairline exactly when every member lies within ``HAIRLINE_DEPTH_MM``. Clusters
and printed depths are reporting only (binary64 / decimal views of the exact
values).

Regenerate with ``pixi run coverage-certificate-omega-star`` (quiet machine
only); ``--render`` re-renders the Markdown from the JSON and refuses a record
of another schema (``StaleOmegaStarRecordError``): such a record must be
re-measured, never rendered.
"""

