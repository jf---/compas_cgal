"""Render the performance history to ``benchmarks/results/perf_history.md`` (included by ``docs/performance.md``).

Follows the rendered-record protocol of ``tests/docs/test_included_records.py``:
``SCHEMA``, ``JSON_PATH``, ``MD_PATH``, ``load_record``, ``render_markdown``.
The rendering is a pure function of the history file, so the docs guard can
re-render it byte for byte.

Per (workload, stage, machine): the baseline (best quiet entry: commit,
date, gated minimum), the latest entry, their ratio, whether the latest is
quiet, and how many entries (quiet / all) the key has.
"""

from __future__ import annotations

from collections.abc import Sequence
from datetime import datetime
from datetime import timezone
from pathlib import Path

from tools.perf_history_baseline import REGRESSION_RATIO_MAX
from tools.perf_history_baseline import baselines
from tools.perf_history_baseline import current_entries
from tools.perf_history_entry import PerfEntry
from tools.perf_history_store import HISTORY_PATH
from tools.perf_history_store import History
from tools.perf_history_store import load_history

SCHEMA = "perf-history/1"
JSON_PATH = HISTORY_PATH
MD_PATH = HISTORY_PATH.with_suffix(".md")
GENERATED_BY = "<!-- Generated by tools/perf_history_render.py from benchmarks/results/perf_history.jsonl. Do not edit; run `pixi run perf-history-render`. -->"
# Hex characters of a commit shown in the table.
SHORT_COMMIT = 8
# Characters of an ISO 8601 time kept as the date.
ISO_DATE = 10
# Rendered precision of seconds: milliseconds.
SECONDS_DECIMALS = 3
# Ordering stand-in for an entry with no recorded time: the earliest possible instant.
_UNTIMED = datetime.min.replace(tzinfo=timezone.utc)


def load_record(path: Path = JSON_PATH) -> History:
    """The history at ``path`` (``tools.perf_history_store.load_history``)."""
    return load_history(path)


def _commit(entry: PerfEntry) -> str:
    commit = entry.provenance.commit
    if commit is not None:
        return f"`{commit[:SHORT_COMMIT]}`" + ("+dirty" if entry.provenance.dirty else "")
    found = entry.source.committed_in
    return "—" if found is None else f"unrecorded (in `{found[:SHORT_COMMIT]}`)"


def _point(entry: PerfEntry) -> str:
    return f"{entry.gated_clock.minimum:.{SECONDS_DECIMALS}f} s · {_commit(entry)} · {entry.when_text[:ISO_DATE] or '—'}"


def _latest(entries: Sequence[tuple[int, PerfEntry]]) -> PerfEntry:
    return max(entries, key=lambda pair: (_UNTIMED if pair[1].when is None else pair[1].when, pair[0]))[1]


def render_markdown(history: History) -> str:
    """The Markdown table of ``history`` (current entries: superseded adapter versions left out)."""
    reference = baselines(history)
    current = current_entries(history.entries)
    groups: dict[tuple[str, str, str], list[tuple[int, PerfEntry]]] = {}
    for index, entry in enumerate(current):
        groups.setdefault(entry.key, []).append((index, entry))
    quiet = sum(1 for entry in current if entry.quiet)
    superseded = len(history.entries) - len(current)
    lines = [
        GENERATED_BY,
        "",
        f"{len(current)} current entries over {len(groups)} (workload, stage, machine) keys; {quiet} quiet; {len(reference)} keys have a baseline; "
        f"{superseded} entries superseded by a newer adapter version; {len(history.rebaselines)} rebaselines.",
        f"Gated value: the minimum of process CPU when the record has it, else wall. Baseline: the best quiet entry since the key's latest rebaseline. "
        f"A quiet entry more than {REGRESSION_RATIO_MAX}x its baseline fails `perf-history-check`.",
        "",
        "| Workload | Stage | Machine | Clock | Baseline (best quiet) | Latest | Latest / baseline | Latest is | Entries (quiet / all) |",
        "|---|---|---|---|---|---|---:|---|---:|",
    ]
    for key in sorted(groups):
        workload, stage, machine = key
        members = groups[key]
        latest = _latest(members)
        baseline = reference.get(key)
        ratio = "—" if baseline is None or baseline.gated_clock.minimum == 0.0 else f"{latest.gated_clock.minimum / baseline.gated_clock.minimum:.2f}"
        state = "quiet" if latest.quiet else f"indicative: {latest.indicative_reason}"
        clock = f"{latest.gated_metric} ({latest.gated_clock.statistic.value}, n={latest.gated_clock.runs})"
        lines.append(
            f"| {workload} | {stage} | {machine} | {clock} | {'none' if baseline is None else _point(baseline)} | {_point(latest)} | {ratio} | {state} "
            f"| {sum(1 for _i, e in members if e.quiet)} / {len(members)} |"
        )
    return "\n".join(lines) + "\n"


def write_markdown(history_path: Path = JSON_PATH, markdown_path: Path = MD_PATH) -> str:
    """Render the history at ``history_path`` to ``markdown_path``; returns the text."""
    text = render_markdown(load_record(history_path))
    markdown_path.write_text(text, encoding="utf-8")
    return text
